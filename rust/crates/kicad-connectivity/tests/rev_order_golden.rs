//! REV-CN: replays the goldens of `tests/oracle/cn_order_oracle.cpp` (`tests/golden/order/`,
//! generated by `gen_cn04.sh`): the `CONNECTIVITY_DATA` queries that have no pcb-dump line,
//! line for line as the reference build answers them after the load path built the
//! connectivity (`pcbnew/connectivity/connectivity_data.cpp`):
//!
//! - `ct` `GetConnectedTracks`, `cp` `GetConnectedPads`, `cpv` `GetConnectedPadsAndVias`,
//!   `net` `GetNetItems`, `zic` `GetZoneIslandConnections`. The C++ orders these by heap
//!   address (`std::set` of pointers, `std::sort` of pointers, `CN_ITEM::m_connected`), which
//!   is neither the allocation order nor stable from run to run in the reference build
//!   (`rust/docs/design/review-connectivity.md`); the oracle prints them in the port's order
//!   (board-model.md 3.1), so the comparison checks the members and the port's order.
//! - `ci<flags>` `GetConnectedItems` (cluster order) for the flag sets 0, `EXCLUDE_ZONES` and
//!   `EXCLUDE_ZONES | IGNORE_NETS`.
//! - `icl` `IsConnectedOnLayer` per copper layer without a type filter (the zone island
//!   branches) and with the types `FlashLayer` passes.
//! - `rn` the ratsnest edges with the items of their ends.
//! - `island` `FillIsolatedIslandsMap( map, true )` for the map `DRC_CACHE_GENERATOR::Run`
//!   builds, in push order.

use std::collections::HashMap;

use kicad_connectivity::algo::IsolatedIslandsMap;
