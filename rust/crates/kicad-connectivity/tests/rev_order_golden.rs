#[test]
fn rev_queries_match_cpp() {
    let mut lines = 0;
    let mut mismatches = Vec::new();
    let mut compared = Vec::new();

    for name in BOARDS {
        let path = format!(
            "{}/tests/golden/order/{name}.txt",
            env!("CARGO_MANIFEST_DIR")
        );
        let golden = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
        let golden: Vec<&str> = golden
            .lines()
            .map(|l| l.strip_prefix("load|").unwrap_or(l))
            .collect();

        let Some(mut board) = load(name) else {
            assert!(
                !name.starts_with("rev_") && !name.starts_with("cn04_"),
                "{name}: synthetic board does not load"
            );
            continue;
        };
        compared.push(*name);
        let rust = rust_lines(name, &mut board);

        // Compare as maps keyed by "<kind>|<key>" so that one difference is one message.
        let key_of = |l: &str| -> String { l.splitn(4, '|').take(3).collect::<Vec<_>>().join("|") };
        let key_of_short = |l: &str| -> String {
            if l.starts_with("q|") {
                key_of(l)
            } else {
                l.splitn(3, '|').take(2).collect::<Vec<_>>().join("|")
            }
        };
        let rust_map: HashMap<String, &str> =
            rust.iter().map(|l| (key_of_short(l), l.as_str())).collect();
        let golden_map: HashMap<String, &str> =
            golden.iter().map(|l| (key_of_short(l), *l)).collect();

        assert_eq!(rust_map.len(), rust.len(), "{name}: duplicate rust keys");
        assert_eq!(
            golden_map.len(),
            golden.len(),
            "{name}: duplicate golden keys"
        );

        for l in &golden {
            lines += 1;

            match rust_map.get(&key_of_short(l)) {
                Some(r) if r == l => {}
                Some(r) => mismatches.push(format!("{name}:\n  rust {r}\n  c++  {l}")),
                None => mismatches.push(format!("{name}:\n  rust -\n  c++  {l}")),
            }
        }

        for l in &rust {
            if !golden_map.contains_key(&key_of_short(l)) {
                mismatches.push(format!("{name}:\n  rust {l}\n  c++  -"));
            }
        }

        // and the order of the lines (the walk orders of the queries)
        if mismatches.is_empty() {
            assert_eq!(rust, golden, "{name}: line order");
        }
    }

    eprintln!(
        "rev order: {} of {} boards compared ({}), {lines} lines, {} mismatches",
        compared.len(),
        BOARDS.len(),
        compared.join(" "),
        mismatches.len()
    );
    assert!(
        mismatches.is_empty(),
        "{} mismatches:\n{}",
        mismatches.len(),
        mismatches.join("\n")
    );
}

/// The layer ids the oracle prints are `PCB_LAYER_ID` values.
#[test]
fn layer_ids_are_the_cpp_values() {
    assert_eq!(PcbLayerId::FCu.0, 0);
    assert_eq!(PcbLayerId::BCu.0, 2);
    assert_eq!(PcbLayerId::In1Cu.0, 4);
}
