/// Parses a board completely: a synthetic board of `tests/golden/cn04/` (`cn04_*`, `rev_*`) or
/// a corpus board. `None` (with a message) when a parser package the board needs has not
/// landed yet (footprints, pads, zones): the board is compared as soon as it parses.
fn load(name: &str) -> Option<Board> {
    let path = if name.starts_with("rev_") || name.starts_with("cn04_") {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests/golden/cn04")
            .join(format!("{name}.kicad_pcb"))
    } else {
        kicad_qa::pcbnew_data_dir().join(format!("{name}.kicad_pcb"))
    };
    let text = std::fs::read_to_string(&path).unwrap();
    let options = ParseOptions {
        allow_pending: true,
    };
    let parsed = std::panic::catch_unwind(|| parse_board_report(&text, "", &options));
    let (board, report) = match parsed {
        Ok(r) => r.unwrap_or_else(|e| panic!("{name}: {}", e.what())),
        Err(e) => {
            let msg = e
                .downcast_ref::<String>()
                .cloned()
                .or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string()))
                .unwrap_or_default();
            assert!(
                msg.contains("port pending"),
                "{name}: parser panicked: {msg}"
            );
            eprintln!("{name}: not compared, the parser reached a model stub: {msg}");
            return None;
        }
    };

    for s in &report.skipped {
        match s.token.as_str() {
            "footprint" | "module" | "pad" | "zone" => {
                eprintln!("{name}: not compared, the parser skipped `{}`", s.token);
                return None;
            }
            "embedded_fonts" | "net_class" | "zone_defaults" | "generated" => {}
            t => panic!("{name}: parser skipped `{t}`: extend the filter"),
        }
    }

    Some(board)
}

/// The oracle's item names: `p<f>.<k>` pad `k` of footprint `f`, `t<i>` `Tracks()[i]`,
/// `z<i>` `Zones()[i]`, `d<i>` `Drawings()[i]`; in the oracle's item order (pads, tracks,
/// zones, drawings).
fn item_names(board: &Board) -> (Vec<ItemId>, HashMap<ItemId, String>) {
    let mut order = Vec::new();
    let mut names = HashMap::new();

    for (f, (fp_id, _)) in board.footprints().enumerate() {
        for (k, (pad_id, _)) in board.footprint_pads(fp_id).enumerate() {
            order.push(pad_id.into());
            names.insert(pad_id.into(), format!("p{f}.{k}"));
        }
    }

    for (i, (id, _)) in board.tracks().enumerate() {
        order.push(id.into());
        names.insert(id.into(), format!("t{i}"));
    }

    for (i, (id, _)) in board.zones().enumerate() {
        order.push(id.into());
        names.insert(id.into(), format!("z{i}"));
    }

    for (i, (id, _)) in board.drawings().enumerate() {
        order.push(id);
        names.insert(id, format!("d{i}"));
    }

    (order, names)
}

fn list(items: impl IntoIterator<Item = String>) -> String {
    format!("[{}]", items.into_iter().collect::<Vec<_>>().join(","))
}

/// The lines the oracle prints for `--queries` in the load phase (`q`, `rn`, `island`).
fn rust_lines(name: &str, board: &mut Board) -> Vec<String> {
    let mut data = ConnectivityData::new();
    assert!(data.build_connectivity(board), "{name}: build");

    let board: &Board = board;
    let bare = BoardCtx::bare(board);
    let (order, names) = item_names(board);
    let nm = |id: ItemId| names.get(&id).cloned().unwrap_or_else(|| "?".to_string());
    let mut out = Vec::new();

    let mut copper_layers = Vec::new();
    Lset::all_cu_mask_n(board.copper_layer_count()).run_on_layers(|l| copper_layers.push(l));

    for &id in &order {
        if !data.algo().item_exists(id) {
            continue;
        }

        let item_type = bare.item(id).unwrap().type_();
        let key = nm(id);

        let ct = data.connected_tracks(id);

        if !ct.is_empty() {
            out.push(format!("q|ct|{key}|{}", list(ct.into_iter().map(nm))));
        }

        let cp = data.connected_pads(id);

        if !cp.is_empty() {
            out.push(format!("q|cp|{key}|{}", list(cp.into_iter().map(nm))));
        }

        let (mut pads, mut vias) = (Vec::new(), Vec::new());
        data.connected_pads_and_vias(id, &mut pads, &mut vias);

        if item_type != KicadT::PcbZoneT && (!pads.is_empty() || !vias.is_empty()) {
            out.push(format!(
                "q|cpv|{key}|{}|{}",
                list(pads.into_iter().map(nm)),
                list(vias.into_iter().map(nm))
            ));
        }

        for flags in [0, EXCLUDE_ZONES, EXCLUDE_ZONES | IGNORE_NETS] {
            let ci = data.connected_items(&bare, id, flags);
            out.push(format!(
                "q|ci{flags}|{key}|{}",
                list(ci.into_iter().map(nm))
            ));
        }

        if item_type == KicadT::PcbViaT || item_type == KicadT::PcbPadT {
            let ctx = BoardCtx::bare(board).with_connectivity(&data);
            let item = ctx.item(id).unwrap();
            let flash_types = [
                KicadT::PcbTraceT,
                KicadT::PcbArcT,
                KicadT::PcbViaT,
                KicadT::PcbPadT,
            ];
            let bits = |types: &[KicadT]| -> String {
                copper_layers
                    .iter()
                    .map(|l| {
                        if data.is_connected_on_layer(&ctx, item, l.0, types) {
                            '1'
                        } else {
                            '0'
                        }
                    })
                    .collect()
            };

            out.push(format!(
                "q|icl|{key}|any={}|flash={}",
                bits(&[]),
                bits(&flash_types)
            ));
        }
    }

    let types = [
        KicadT::PcbTraceT,
        KicadT::PcbArcT,
        KicadT::PcbViaT,
        KicadT::PcbZoneT,
        KicadT::PcbPadT,
        KicadT::PcbShapeT,
    ];

    for net in 0..data.net_count() {
        let ni = data.net_items(net, &types);

        if !ni.is_empty() {
            out.push(format!("q|net|{net}|{}", list(ni.into_iter().map(nm))));
        }
    }

    for (zone_id, zone) in board.zones() {
        let id: ItemId = zone_id.into();

        if !data.algo().item_exists(id) {
            continue;
        }

        let mut layers = Vec::new();
        zone.layer_set(&bare).run_on_layers(|l| layers.push(l));

        for layer in layers {
            let islands = data.zone_island_connections(id, layer);

            if !islands.is_empty() {
                let text: String = islands
                    .into_iter()
                    .map(|island| list(island.into_iter().map(nm)))
                    .collect();
                out.push(format!("q|zic|{}/{}|{text}", nm(id), layer.0));
            }
        }
    }

    // the ratsnest: GetEdges() order, "<x>,<y>@<item>" per end
    for net in 0..data.net_count() {
        if data
            .ratsnest_for_net(net)
            .is_none_or(|n| n.node_count() == 0)
        {
            continue;
        }

        let edges = data.net_edges(net).to_vec();
        let item_list = data.item_list();
        let anchor = |a: &CnAnchor| {
            let item = item_list.item(a.item().unwrap());
            let mut r = nm(item.parent());

            if let Some(zl) = item.zone_layer() {
                r = format!("{r}/{}/{}", zl.layer().0, zl.subpoly_index());
            }

            format!("{},{}@{r}", a.pos().x, a.pos().y)
        };

        let text = list(edges.iter().map(|e| {
            format!(
                "{}>{}:{}",
                anchor(e.source_anchor(item_list).unwrap()),
                anchor(e.target_anchor(item_list).unwrap()),
                e.weight()
            )
        }));

        if text != "[]" {
            out.push(format!("rn|n{net}|{text}"));
        }
    }

    // FillIsolatedIslandsMap( map, true ) with the map of DRC_CACHE_GENERATOR::Run
    let mut map = IsolatedIslandsMap::new();

    for (zone_id, zone) in board.zones() {
        if !zone.is_rule_area
            && zone.teardrop_type == TeardropType::TdNone
            && !zone.is_copper_thieving()
        {
            zone.layer_set(&bare).run_on_layers(|layer| {
                map.entry(zone_id)
                    .or_default()
                    .insert(layer, IsolatedIslands::default());
            });
        }
    }

    data.fill_isolated_islands_map(&bare, &mut map, true);

    for (zone_id, _) in board.zones() {
        let Some(layers) = map.get(&zone_id) else {
            continue;
        };

        for (layer, isl) in layers {
            let ints = |v: &[i32]| list(v.iter().map(|i| i.to_string()));
            out.push(format!(
                "island|{}/{}|isolated={}|single={}",
                nm(zone_id.into()),
                layer.0,
                ints(&isl.isolated_outlines),
                ints(&isl.single_connection_outlines)
            ));
        }
    }

    out
}

