//! CN-05: replays the goldens of `tests/oracle/ft_cache_oracle.cpp` (`tests/golden/ft_cache/`,
//! generated by `gen_ft_cache.sh` for the boards of `tests/oracle/ft_cache_boards.txt`):
//! `FROM_TO_CACHE::Rebuild` and `IsOnFromToPath` (`pcbnew/connectivity/from_to_cache.cpp`) of
//! the reference build for generated `(from, to)` pad pairs of every net with at least two
//! pads, asked for every pad, track and zone of the board, through
//! `ConnectivityQuery::is_on_from_to_path` (the `fromTo()` entry point).
//!
//! Where the heap order of `CN_ITEM::m_connected` decides between two paths, the golden also
//! carries `list=`: the C++ search replayed in CN list order (the port's order); the port must
//! give that one. Everywhere else it must give the reference's own answer (`real=`).

use std::collections::HashMap;
use std::path::PathBuf;

use kicad_connectivity::data::ConnectivityData;
use kicad_pcb::Board;
use kicad_pcb::ctx::{BoardCtx, ConnectivityQuery};
use kicad_pcb::ids::ItemId;
use kicad_pcb::io::{ParseOptions, parse_board_report};

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// The boards (paths relative to `<kicad>` without extension) of `ft_cache_boards.txt`.
fn boards() -> Vec<String> {
    let text =
        std::fs::read_to_string(manifest_dir().join("tests/oracle/ft_cache_boards.txt")).unwrap();

    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_string)
        .collect()
}

/// Parses a board completely; `None` (with a message) when a parser package the board needs
/// has not landed yet (as `rev_order_golden.rs`).
fn load(rel: &str) -> Option<Board> {
    let path = kicad_qa::kicad_source_root().join(format!("{rel}.kicad_pcb"));
    let text = std::fs::read_to_string(&path).unwrap();
    let options = ParseOptions {
        allow_pending: true,
    };
    let parsed = std::panic::catch_unwind(|| parse_board_report(&text, "", &options));
    let (board, report) = match parsed {
        Ok(r) => r.unwrap_or_else(|e| panic!("{rel}: {}", e.what())),
        Err(e) => {
            let msg = e
                .downcast_ref::<String>()
                .cloned()
                .or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string()))
                .unwrap_or_default();
            assert!(
                msg.contains("port pending"),
                "{rel}: parser panicked: {msg}"
            );
            eprintln!("{rel}: not compared, the parser reached a model stub: {msg}");
            return None;
        }
    };

    for s in &report.skipped {
        match s.token.as_str() {
            "footprint" | "module" | "pad" | "zone" => {
                eprintln!("{rel}: not compared, the parser skipped `{}`", s.token);
                return None;
            }
            _ => {}
        }
    }

    Some(board)
}

/// The oracle's item names in its order: `p<f>.<k>` pads, `t<i>` tracks, `z<i>` zones.
fn item_names(board: &Board) -> Vec<(ItemId, String)> {
    let mut items = Vec::new();

    for (f, (fp_id, _)) in board.footprints().enumerate() {
        for (k, (pad_id, _)) in board.footprint_pads(fp_id).enumerate() {
            items.push((pad_id.into(), format!("p{f}.{k}")));
        }
    }

    for (i, (id, _)) in board.tracks().enumerate() {
        items.push((id.into(), format!("t{i}")));
    }

    for (i, (id, _)) in board.zones().enumerate() {
        items.push((id.into(), format!("z{i}")));
    }

    items
}

/// One `ft|` line of the golden.
struct FtLine {
    from: String,
    to: String,
    real: String,
    paths: usize,
    unique: String,
    list: Option<String>,
}

fn parse_line(line: &str) -> FtLine {
    let f: Vec<&str> = line.split('|').collect();
    let field = |prefix: &str| -> Option<String> {
        f.iter()
            .skip(3)
            .find_map(|s| s.strip_prefix(prefix).map(str::to_string))
    };

    FtLine {
        from: f[1].to_string(),
        to: f[2].to_string(),
        real: field("real=").expect("real="),
        paths: field("paths=").expect("paths=").parse().unwrap(),
        unique: field("unique=").expect("unique="),
        list: field("list="),
    }
}

#[test]
fn cn05_from_to_cache_matches_reference() {
    let mut compared_boards = 0;
    let mut compared_pairs = 0;
    let mut heap_order_pairs = 0;
    let mut failures = Vec::new();

    for rel in boards() {
        let name = rel.rsplit('/').next().unwrap().to_string();
        let golden_path = manifest_dir().join(format!("tests/golden/ft_cache/{name}.txt"));
        let golden = std::fs::read_to_string(&golden_path).unwrap();
        let lines: Vec<FtLine> = golden
            .lines()
            .filter(|l| l.starts_with("ft|"))
            .map(parse_line)
            .collect();

        assert!(
            !golden.lines().any(|l| l.starts_with("error|")),
            "{name}: the oracle failed on this board"
        );

        if lines.is_empty() {
            continue;
        }

        let Some(mut board) = load(&rel) else {
            continue;
        };

        let mut data = ConnectivityData::new();
        assert!(data.build_connectivity(&mut board), "{name}: build");
        data.rebuild_from_to_cache(&BoardCtx::bare(&board));

        let board: &Board = &board;
        let names = item_names(board);
        let ctx = BoardCtx::bare(board).with_connectivity(&data);
        let index: HashMap<ItemId, usize> = names
            .iter()
            .enumerate()
            .map(|(i, (id, _))| (*id, i))
            .collect();

        for line in &lines {
            let mut on_path = Vec::new();

            for (id, nm) in &names {
                let item = ctx.item(*id).unwrap();

                if data
                    .is_on_from_to_path(&ctx, item, &line.from, &line.to)
                    .expect("ConnectivityData has a from-to cache")
                {
                    on_path.push(nm.clone());
                }
            }

            let got = format!("[{}]", on_path.join(","));

            let cache = data.from_to_cache();
            let paths: Vec<_> = cache
                .paths()
                .iter()
                .filter(|p| p.from_wildcard == line.from && p.to_wildcard == line.to)
                .collect();
            let unique = format!(
                "[{}]",
                paths
                    .iter()
                    .map(|p| if p.is_unique { "1" } else { "0" })
                    .collect::<Vec<_>>()
                    .join(",")
            );

            // Path items outside the named items (none expected) would be invisible above
            for p in &paths {
                for item in &p.path_items {
                    assert!(
                        index.contains_key(item),
                        "{name}: path item {item:?} unnamed"
                    );
                }
            }

            let expected = line.list.as_ref().unwrap_or(&line.real);

            if line.list.is_some() {
                heap_order_pairs += 1;
            }

            // `unique=` comes from the list-order replay (isUnique depends on the neighbour
            // order as well)
            if got != *expected || paths.len() != line.paths || unique != line.unique {
                failures.push(format!(
                    "{name}: {} -> {}: got {got} paths={} unique={unique}, expected {expected} \
                     paths={} unique={}",
                    line.from,
                    line.to,
                    paths.len(),
                    line.paths,
                    line.unique
                ));
            }

            compared_pairs += 1;
        }

        compared_boards += 1;
    }

    eprintln!(
        "cn05: {compared_boards} boards, {compared_pairs} pairs ({heap_order_pairs} decided by \
         the C++ heap order, compared with the list-order replay), {} mismatches",
        failures.len()
    );

    assert!(
        failures.is_empty(),
        "{} mismatches:\n{}",
        failures.len(),
        failures.join("\n")
    );
    assert!(
        compared_boards >= 30,
        "only {compared_boards} boards compared"
    );
}
