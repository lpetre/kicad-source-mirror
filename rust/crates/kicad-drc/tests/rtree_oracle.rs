const WORST: i32 = 200000;

fn golden() -> String {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/rtree_oracle.txt");
    std::fs::read_to_string(path).expect("golden rtree_oracle.txt")
}

fn join(list: &[String]) -> String {
    list.join(",")
}

