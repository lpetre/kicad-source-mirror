//! Replay of the DRC-02 differential oracle (`tests/oracle/drc_rtree_oracle.cpp`, golden
//! `tests/golden/rtree_oracle.txt`, regenerated by `tests/oracle/gen_rtree_goldens.sh`).
//!
//! The C++ driver runs the real `DRC_RTREE`, `DRC_ZONE_INDEX`, `CollectOverlappingPairs` and
//! `DRC_TEST_PROVIDER` code of the reference build. Line format (`|`-separated; items are named
//! `#n`, their ordinal in `forEachGeometryItem( {}, AllLayersMask )`; tree entries `#n:sub`
//! with sub `-` = whole shape, `h` = pad hole, `i` = indexable sub-shape i):
//!
//! * `registry|i|name`, `basic|types`, `basicbz|types`, `name|base name`: provider registry,
//!   `s_allBasicItems`, `s_allBasicItemsButZones`, `GetName()`.
//! * `fmt|units|type|c|a|msg`, `fmtx|...` (additional parameter), `fmta|units|c|a|msg` (angles):
//!   `formatMsg`.
//! * `cop|seed|n|pairs`: `CollectOverlappingPairs` on pseudo-random boxes.
//! * per board: `walk|case|n|items` (forEachGeometryItem), `tree|size|n|empty`,
//!   `onlayer|layer|entries` (storage order), `qc|item|layer|clr|count|hits`
//!   (QueryColliding), `qcf|...|filter calls|hits` (with filter and stopping visitor),
//!   `ovl|item|layer|clr|entries` (raw search order over the query box),
//!   `qp|item|layer|clr|credit|count|hits` (QueryCollidingPreparedCopper), `cc|...`
//!   (CheckColliding), `at|item|layer|clr|items` (GetObjectsAt, sorted: C++ returns an
//!   unordered set), `pair|i|layers|ref|test|collides` and `pairstop|visits|progress calls`
//!   (QueryCollidingPairs), `ztree|zq|zqb|zqp|zidx` (zone trees and the zone index).
//!
//! A board whose replay reaches a `port_pending!` stub of another package (item shapes of pads,
//! zones, graphics) is reported as pending and compared automatically once they land.

