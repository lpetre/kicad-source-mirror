#[test]
fn registry_and_type_lists() {
    let golden = golden();
    let mut registry = Vec::new();

    for line in golden.lines() {
        let f: Vec<&str> = line.split('|').collect();

        match f[0] {
            "registry" => registry.push(f[2].to_string()),
            "basic" | "basicbz" => {
                let list = if f[0] == "basic" {
                    all_basic_items()
                } else {
                    all_basic_items_but_zones()
                };
                let ours: Vec<String> = list.iter().map(|&t| (t as i32).to_string()).collect();
                assert_eq!(join(&ours), f[1], "{}", f[0]);
            }
            "name" => assert_eq!(DrcTestProviderBase::default().name, f[1]),
            _ => {}
        }
    }

    let ours: Vec<String> = DRC_TEST_PROVIDERS
        .iter()
        .map(|p| p.name.to_string())
        .collect();
    assert_eq!(ours, registry);
}

fn units_of(n: i32) -> EdaUnits {
    *EdaUnits::ALL
        .iter()
        .find(|&&u| u as i32 == n)
        .expect("known EDA_UNITS")
}

fn data_type_of(name: &str) -> EdaDataType {
    match name {
        "distance" => EdaDataType::Distance,
        "area" => EdaDataType::Area,
        "volume" => EdaDataType::Volume,
        "unitless" => EdaDataType::Unitless,
        "time" => EdaDataType::Time,
        "length_delay" => EdaDataType::LengthDelay,
        _ => panic!("unknown data type {name}"),
    }
}

#[test]
fn format_msg() {
    let golden = golden();
    let mut n = 0;

    for line in golden.lines() {
        let f: Vec<&str> = line.splitn(6, '|').collect();
        let mut prov = DrcTestProviderBase::default();

        match f[0] {
            "fmt" | "fmtx" => {
                prov.set_user_units(units_of(f[1].parse().unwrap()));
                let t = data_type_of(f[2]);
                let c: f64 = f[3].parse().unwrap();
                let a: f64 = f[4].parse().unwrap();

                let msg = if f[0] == "fmt" {
                    prov.format_msg(
                        "(%s clearance %s; actual %s)",
                        "netclass 'Default'",
                        c,
                        a,
                        t,
                    )
                } else {
                    prov.format_msg_extra(
                        "(%s min diameter %s; actual %s on %s)",
                        "board setup",
                        c,
                        a,
                        "F.Cu",
                        t,
                    )
                };

                assert_eq!(msg, f[5], "{line}");
                n += 1;
            }
            "fmta" => {
                let f: Vec<&str> = line.splitn(5, '|').collect();
                prov.set_user_units(units_of(f[1].parse().unwrap()));
                let c: f64 = f[2].parse().unwrap();
                let a: f64 = f[3].parse().unwrap();
                let msg = prov.format_msg_angle("(%s max angle %s; actual %s)", "rule 'a'", c, a);
                assert_eq!(msg, f[4], "{line}");
                n += 1;
            }
            _ => {}
        }
    }

    assert_eq!(n, 1096);
}

#[test]
fn collect_overlapping_pairs_oracle() {
    let golden = golden();
    let mut n = 0;

    for line in golden.lines().filter(|l| l.starts_with("cop|")) {
        let f: Vec<&str> = line.split('|').collect();
        let seed: u32 = f[1].parse().unwrap();
        let mut state: u32 = seed.wrapping_mul(2654435761);
        let mut next = |m: i32| -> i32 {
            state = state.wrapping_mul(1664525).wrapping_add(1013904223);
            ((state >> 8) % m as u32) as i32
        };

        let count = 20 + 25 * seed as usize;
        let mut boxes = Vec::new();
        let mut has = Vec::new();

        for b in 0..count {
            let x = next(1000) - 200;
            let y = next(1000) - 200;
            let w = next(120) - 20;
            let h = next(120) - 20;
            boxes.push(Box2I::new(
                Vector2I::new(x, y),
                Vector2L::new(w as i64, h as i64),
            ));
            has.push(b % 7 != 3);
        }

        for _ in 0..2 {
            boxes.push(Box2I::new(Vector2I::new(0, 0), Vector2L::new(0, 0)));
            has.push(true);
        }

        let order: Vec<usize> = (0..boxes.len())
            .map(|b| (b * 7 + seed as usize) % boxes.len())
            .collect();

        let pairs = collect_overlapping_pairs(&order, |i| has[i].then_some(boxes[i]));
        let out: Vec<String> = pairs.iter().map(|(a, b)| format!("{a}-{b}")).collect();

        assert_eq!(boxes.len().to_string(), f[2]);
        assert_eq!(join(&out), f[3], "seed {seed}");
        n += 1;
    }

    assert_eq!(n, 3);
}

