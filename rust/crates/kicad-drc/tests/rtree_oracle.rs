/// The golden lines of each board, in order.
fn golden_boards() -> Vec<(String, Vec<String>)> {
    let mut boards: Vec<(String, Vec<String>)> = Vec::new();

    for line in golden().lines() {
        if let Some(name) = line.strip_prefix("board|") {
            boards.push((name.to_string(), Vec::new()));
        } else if let Some((_, lines)) = boards.last_mut() {
            lines.push(line.to_string());
        }
    }

    boards
}

