fn golden() -> String {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/cachegen_oracle.txt");
    std::fs::read_to_string(path).expect("golden cachegen_oracle.txt")
}

fn golden_boards() -> Vec<(String, Vec<String>)> {
    let mut boards: Vec<(String, Vec<String>)> = Vec::new();

    for line in golden().lines() {
        if let Some(name) = line.strip_prefix("board|") {
            boards.push((name.to_string(), Vec::new()));
        } else if let Some((_, lines)) = boards.last_mut() {
            lines.push(line.to_string());
        }
    }

    boards
}

fn board_path(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data");

    for sub in ["rtree", "cachegen"] {
        let local = dir.join(sub).join(name);

        if local.exists() {
            return local;
        }
    }

    kicad_qa::pcbnew_data_dir().join(name)
}

/// FNV-1a 64, as the driver's `fnv()`.
fn fnv(text: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;

    for b in text.bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }

    format!("{h:016x}")
}

/// The ordinals of the items (`#n`).
struct Keys(HashMap<ItemId, usize>);

impl Keys {
    fn key(&self, id: ItemId) -> String {
        match self.0.get(&id) {
            Some(n) => format!("#{n}"),
            None => "?".to_string(),
        }
    }

    fn entry(&self, e: &ItemWithShape) -> String {
        let sub = if e.shape_storage.is_some() {
            "h".to_string()
        } else {
            match e.sub {
                None => "-".to_string(),
                Some(i) => i.to_string(),
            }
        };

        format!("{}:{}", self.key(e.parent), sub)
    }

    fn entries(&self, tree: &DrcRtree, layer: PcbLayerId) -> Vec<String> {
        tree.on_layer(layer)
            .into_iter()
            .map(|e| self.entry(e))
            .collect()
    }
}

fn box_str(b: &Box2I) -> String {
    format!("{} {} {} {}", b.x(), b.y(), b.right(), b.bottom())
}

/// The load path of the driver (`KI_TEST::LoadBoard`): parse, the sibling project's design
/// and net settings, `InitEngine` with the sibling rule file. User rule conditions are compiled
/// with the stand-in binding of the DRC-20 tests (the conditions are only compiled here; the
/// cache generator reads `condition.is_some()`). Tuning profiles are not read (none of the
/// boards has one).
fn load_board(path: &Path) -> Result<(Board, DrcEngine), String> {
    let text =
        String::from_utf8_lossy(&std::fs::read(path).map_err(|e| e.to_string())?).to_string();
    let name = path.file_name().unwrap().to_string_lossy().to_string();
    let mut board =
        parse_board(&text, &name, &ParseOptions::default()).map_err(|e| format!("{e}"))?;

    let pro = path.with_extension("kicad_pro");

    if pro.exists() {
        let doc = json::parse_bytes(&std::fs::read(&pro).unwrap(), ObjectOrder::Sorted, true)
            .map_err(|e| format!("project: {e:?}"))?;
        let mut parent = JsonSettingsInternals {
            original: doc.clone(),
            doc,
        };

        if !board.legacy_design_settings_loaded {
            let _ = load_board_design_settings(
                &mut parent,
                board.design_settings_mut(),
                std::rc::Rc::new(KiapiDrcExclusionCodec::default()),
            );
        }

        let (net_settings, _) = load_net_settings(Some(&parent));
        board.design_settings_mut().net_settings = net_settings;
        board.project = Some(BoardProject::default());
    }

    let dru = path.with_extension("kicad_dru");
    let dru_text = dru
        .exists()
        .then(|| String::from_utf8_lossy(&std::fs::read(&dru).unwrap()).to_string());
    let dru_path = dru.to_string_lossy().to_string();

    let mut engine = DrcEngine::new();
    engine
        .init_engine_with::<SyntaxBinder>(
            &mut board,
            dru_text.as_deref().map(|t| (t, dru_path.as_str())),
            default_layer_choices(),
            &TuningProfiles::default(),
            None,
        )
        .map_err(|e| format!("init_engine: {e:?}"))?;

    Ok((board, engine))
}

/// The driver's `runCacheGen` on the Rust side.
fn replay_board(path: &Path) -> Result<Vec<String>, String> {
    let (mut board, engine) = load_board(path)?;
    let mut out = Vec::new();
    let mut keys = Keys(HashMap::new());

    {
        let ctx = BoardCtx::bare(&board).with_rules(&engine);
        let mut types = Vec::new();

        for_each_geometry_item(&ctx, &[], Lset::all_layers_mask(), |item| {
            let ord = keys.0.len();
            keys.0.insert(item.id().expect("board item"), ord);
            types.push((item.type_() as i32).to_string());
            true
        });

        out.push(format!("cg|keys|{}", types.join(",")));
    }

    prepare_board(&mut board);

    let ctx = BoardCtx::bare(&board).with_rules(&engine);
    let mut caches = DrcBoardCaches::new();

    (caches.max_clearance, caches.max_physical_clearance) = compute_max_clearances(&ctx, &engine);
    build_zone_lists(&ctx, &mut caches);
    caches.copper_item_rtree = Some(std::sync::Arc::new(build_copper_item_rtree(
        &ctx,
        caches.max_clearance,
    )));
    build_zone_caches(&ctx, &mut caches);
    init_zone_islands_map(&ctx, &mut caches.zone_isolated_islands);

    let zone_keys = |list: &[kicad_pcb::ids::ZoneId]| -> String {
        list.iter()
            .map(|&z| keys.key(z.into()))
            .collect::<Vec<_>>()
            .join(",")
    };

    out.push("cg|run|1".to_string());
    out.push(format!(
        "cg|bds_biggest|{}",
        board
            .design_settings()
            .get_biggest_clearance_value(Some(&engine))
    ));
    out.push(format!(
        "cg|board_max|{}",
        board.get_max_clearance_value(&ctx)
    ));
    out.push(format!("cg|max_clearance|{}", caches.max_clearance));
    out.push(format!("cg|max_physical|{}", caches.max_physical_clearance));
    out.push(format!("cg|zones|{}", zone_keys(&caches.zones)));
    out.push(format!(
        "cg|copper_zones|{}",
        zone_keys(&caches.copper_zones)
    ));

    for (layer, zones) in &caches.copper_zones_by_layer {
        out.push(format!(
            "cg|zones_by_layer|{}|{}",
            layer.0,
            zone_keys(zones)
        ));
    }

    let tree = caches.copper_item_rtree();
    out.push(format!(
        "cg|tree|{}|{}",
        tree.len(),
        if tree.is_empty() { 1 } else { 0 }
    ));

    Lset::all_cu_mask_n(board.copper_layer_count()).run_on_layers(|layer| {
        out.push(format!(
            "cg|onlayer|{}|{}",
            layer.0,
            keys.entries(tree, layer).join(",")
        ));
    });

    for (zone_id, _) in zones_in_drc_order(&board) {
        let zone = board.zone(zone_id).unwrap();
        let k = keys.key(zone_id.into());

        out.push(format!(
            "cg|zbbox|{k}|{}",
            box_str(&zone.bounding_box(&ctx))
        ));

        let Some(ztree) = caches.copper_zone_rtree(zone_id) else {
            continue;
        };

        out.push(format!("cg|ztree|{k}|{}", ztree.len()));

        for l in 0..kicad_core::layer_ids::PCB_LAYER_ID_COUNT {
            let list = keys.entries(ztree, PcbLayerId(l));

            if !list.is_empty() {
                out.push(format!(
                    "cg|ztree_layer|{k}|{l}|{}|{}",
                    list.len(),
                    fnv(&list.join(","))
                ));
            }
        }
    }

    for (zone_id, _) in board.zones() {
        if let Some(layers) = caches.zone_islands(zone_id) {
            let list: Vec<String> = layers.keys().map(|l| l.0.to_string()).collect();
            out.push(format!(
                "cg|islands|{}|{}",
                keys.key(zone_id.into()),
                list.join(",")
            ));
        }
    }

    Ok(out)
}

fn panic_text(e: &(dyn std::any::Any + Send)) -> String {
    e.downcast_ref::<String>()
        .cloned()
        .or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string()))
        .unwrap_or_default()
}

/// Runs `f`, turning a `port_pending!` panic (or a load error naming one) into `Err`.
fn run_or_pending<R>(f: impl FnOnce() -> Result<R, String>) -> Result<R, String> {
    match catch_unwind(AssertUnwindSafe(f)) {
        Ok(Ok(r)) => Ok(r),
        Ok(Err(e)) if e.contains("port pending") || e.contains("pending") => Err(e),
        Ok(Err(e)) => panic!("load error {e}"),
        Err(e) => {
            let msg = panic_text(e.as_ref());

            if msg.contains("port pending") {
                Err(msg)
            } else {
                std::panic::resume_unwind(e)
            }
        }
    }
}

#[test]
fn cache_generator_oracle_replay() {
    let mut compared = BTreeMap::new();
    let mut pending = BTreeMap::new();

    for (name, golden_lines) in golden_boards() {
        let path = board_path(&name);

        let ours = match run_or_pending(|| replay_board(&path)) {
            Ok(lines) => lines,
            Err(e) => {
                pending.insert(name, e);
                continue;
            }
        };

        for (i, (g, o)) in golden_lines.iter().zip(ours.iter()).enumerate() {
            assert_eq!(o, g, "{name}: line {i}");
        }

        assert_eq!(ours.len(), golden_lines.len(), "{name}: line count");
        compared.insert(name, ours.len());
    }

    eprintln!("cache generator oracle: compared {compared:?}");
    eprintln!("cache generator oracle: pending {pending:?}");

    // The synthetic boards (tracks, arcs, vias; rule files for the physical / clearance
    // branches) must replay today.
    for name in [
        "rtree_small.kicad_pcb",
        "rtree_ties.kicad_pcb",
        "rtree_4layer.kicad_pcb",
        "phys_cond.kicad_pcb",
        "phys_uncond.kicad_pcb",
        "huge.kicad_pcb",
    ] {
        assert!(
            compared.contains_key(name),
            "{name} did not replay: {pending:?}"
        );
    }
}

/// Port of `qa/tests/pcbnew/drc/test_drc_physical_clearance.cpp`
/// (`DRCPhysicalClearanceNotInflatedByConditionalRules`, regression test for issue 22996): a
/// board without physical clearance rules and without barcodes has
/// `m_DRCMaxPhysicalClearance == 0` after the cache generation, although the implicit barcode
/// rule adds a conditional `PHYSICAL_CLEARANCE_CONSTRAINT`. The C++ test runs the whole DRC on
/// `issue4139`; the cache generator part is replayed here (pending until the board loads).
#[test]
fn drc_physical_clearance_not_inflated_by_conditional_rules() {
    let path = kicad_qa::pcbnew_data_dir().join("issue4139.kicad_pcb");

    let result = run_or_pending(|| {
        let (mut board, engine) = load_board(&path)?;
        prepare_board(&mut board);
        let ctx = BoardCtx::bare(&board).with_rules(&engine);
        Ok(compute_max_clearances(&ctx, &engine))
    });

    match result {
        Ok((_, physical)) => assert_eq!(physical, 0),
        Err(e) => eprintln!("issue4139 pending: {e}"),
    }

    // The same property on a board that loads today (the implicit barcode rule exists, no
    // barcode on the board).
    let (mut board, engine) = load_board(&board_path("rtree_small.kicad_pcb")).unwrap();
    assert!(
        engine
            .query_worst_constraint(
                kicad_drc::DrcConstraintT::PhysicalClearanceConstraint,
                false
            )
            .is_some()
    );
    prepare_board(&mut board);
    let ctx = BoardCtx::bare(&board).with_rules(&engine);
    assert_eq!(compute_max_clearances(&ctx, &engine).1, 0);
}
