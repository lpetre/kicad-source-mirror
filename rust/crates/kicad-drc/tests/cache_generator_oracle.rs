//! Replay of the DRC-05 differential oracle: `drc-rtree-oracle --cachegen`
//! (`tests/oracle/drc_rtree_oracle.cpp`, `runCacheGen`; golden `tests/golden/cachegen_oracle.txt`,
//! regenerated by `tests/oracle/gen_cachegen_goldens.sh`).
//!
//! The C++ driver loads each board like `KI_TEST::LoadBoard` (sibling project, `InitEngine`
//! with the sibling rule file, nets, connectivity), runs the real `DRC_CACHE_GENERATOR::Run()`
//! and prints the `BOARD` caches. Line format (`|`-separated; items are `#n`, their ordinal in
//! `forEachGeometryItem( {}, AllLayersMask )`; tree entries `#n:sub` as in `rtree_oracle.rs`):
//!
//! * `cg|keys|types`, `cg|run|ok`;
//! * `cg|bds_biggest|n` (`GetBiggestClearanceValue`), `cg|board_max|n` (`GetMaxClearanceValue`),
//!   `cg|max_clearance|n`, `cg|max_physical|n` (`m_DRCMaxClearance`,
//!   `m_DRCMaxPhysicalClearance`);
//! * `cg|zones|keys`, `cg|copper_zones|keys`, `cg|zones_by_layer|layer|keys`;
//! * `cg|tree|size|empty`, `cg|onlayer|layer|entries` (the copper item tree, storage order);
//! * per zone `cg|zbbox|zone|box`, and for a zone with a copper tree `cg|ztree|zone|size`,
//!   `cg|ztree_layer|zone|layer|count|fnv` (FNV-1a 64 of the entry list);
//! * `cg|islands|zone|layers` (`m_ZoneIsolatedIslandsMap` keys).
//!
//! The Rust side runs the phases of [`kicad_drc::cache_generator`] that do not depend on
//! unported packages: [`prepare_board`], [`compute_max_clearances`], [`build_zone_lists`],
//! [`build_copper_item_rtree`], [`build_zone_caches`], [`init_zone_islands_map`]. The courtyard
//! caches, the board outline and the connectivity rebuild (pending in kicad-pcb /
//! kicad-connectivity) leave no trace in the dump. A board whose replay reaches a
//! `port_pending!` stub is reported as pending and compared automatically once it loads.

