impl<'a> AnyItem<'a> {
    /// `dynamic_cast<BOARD_CONNECTED_ITEM*>`: pads, tracks / arcs / vias, zones, shapes and
    /// the shape-derived textbox and table cell.
    pub fn as_connected(&self) -> Option<&'a dyn BoardConnectedItem> {
        match *self {
            AnyItem::Pad(x) => Some(x),
            AnyItem::Track(x) => Some(x),
            AnyItem::Zone(x) => Some(x),
            AnyItem::Shape(x) => Some(x),
            AnyItem::Textbox(x) => Some(x),
            AnyItem::Tablecell(x) => Some(x),
            _ => None,
        }
    }
}

/// Owned item outside any arena: a leaf value on its way into `Board::add` / `footprint_add`,
/// generator templates. The `Footprint` and `Table` variants are data carriers for the deferred
/// deep copy between boards (`board-model.md` 17); tier 1/2 code creates containers in place.
#[derive(Clone, Debug)]
pub enum OwnedItem {
    Footprint(Box<FootprintTree>),
    Pad(Box<Pad>),
    Track(Track),
    Zone(Box<Zone>),
    Shape(Box<PcbShape>),
    Text(Box<PcbText>),
    Field(Box<PcbField>),
    Textbox(Box<PcbTextbox>),
    Table(Box<TableTree>),
    Dimension(Box<PcbDimension>),
    Barcode(Box<PcbBarcode>),
    Image(Box<PcbReferenceImage>),
    Target(PcbTarget),
    Point(PcbPoint),
    Group(PcbGroup),
    Generator(Box<PcbGenerator>),
    Marker(Box<PcbMarker>),
    Constraint(PcbConstraint),
    Body3d(Box<Pcb3dBody>),
    GridItem(Box<PcbGridItem>),
    DrillMap(Box<PcbDrillMap>),
}

/// DEFERRED behaviour, data only. A footprint with its children by value (the child-list
/// fields of `footprint` are empty and are rebuilt on insertion). Group members inside the tree
/// are referenced by Kiid (`group_members`), resolved when the tree is added. Will port the
/// deep copy of the C++ FOOTPRINT copy constructor (its ptrMap becomes the Kiid map).
#[derive(Clone, Debug)]
pub struct FootprintTree {
    pub footprint: Footprint,
    pub fields: Vec<PcbField>,    // C++ m_fields order
    pub pads: Vec<Pad>,           // m_pads order
    pub drawings: Vec<OwnedItem>, // m_drawings order
    pub zones: Vec<Zone>,
    pub groups: Vec<PcbGroup>,
    pub constraints: Vec<PcbConstraint>,
    pub points: Vec<PcbPoint>,
    pub bodies: Vec<Pcb3dBody>,
    pub group_members: Vec<(Kiid, Vec<Kiid>)>, // (group uuid, member uuids)
}

/// DEFERRED behaviour, data only: a table with its cells by value.
#[derive(Clone, Debug)]
pub struct TableTree {
    pub table: PcbTable,
    pub cells: Vec<PcbTablecell>,
}

/// The Rust spelling of a `BOARD_ITEM*` parameter: context + item (+ its handle, read from
/// `base.id`; for `AnyItem::Net` the `ItemKind::Net` form).
#[derive(Clone, Copy)]
pub struct ItemRef<'a> {
    pub ctx: &'a BoardCtx<'a>,
    item: AnyItem<'a>,
    hole_proxy: bool,
}

impl std::fmt::Debug for ItemRef<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ItemRef")
            .field("kind", &self.item.kind())
            .field("id", &self.id())
            .field("uuid", &self.uuid())
            .field("hole_proxy", &self.hole_proxy)
            .finish()
    }
}

impl PartialEq for ItemRef<'_> {
    /// Pointer equality: same handle, or the same address for values without a handle.
    fn eq(&self, other: &Self) -> bool {
        match (self.id(), other.id()) {
            (Some(a), Some(b)) => a == b,
            (None, None) => std::ptr::addr_eq(
                self.as_dyn() as *const dyn BoardItem,
                other.as_dyn() as *const dyn BoardItem,
            ),
            _ => false,
        }
    }
}

impl<'a> ItemRef<'a> {
    pub(crate) fn new(ctx: &'a BoardCtx<'a>, item: AnyItem<'a>) -> Self {
        ItemRef {
            ctx,
            item,
            hole_proxy: false,
        }
    }

    // ---- identity ----

    /// The item's handle; `None` for detached / inline values.
    pub fn id(&self) -> Option<ItemId> {
        match self.item {
            AnyItem::Net(net) => ItemId::net(net.net_code),
            _ => self.item.base().id(),
        }
    }

    /// `m_Uuid`.
    pub fn uuid(&self) -> Kiid {
        self.item.base().uuid
    }

    /// `Type()`.
    pub fn type_(&self) -> KicadT {
        self.as_dyn().type_()
    }

    /// The `EDA_ITEM` / `BOARD_ITEM` data members.
    pub fn base(&self) -> &'a BoardItemBase {
        self.item.base()
    }

    /// The `match`-able item.
    pub fn any(&self) -> AnyItem<'a> {
        self.item
    }

    /// The item as a trait object.
    pub fn as_dyn(&self) -> &'a dyn BoardItem {
        self.item.as_dyn()
    }

    // ---- downcasts (static_cast / dynamic_cast) ----

    /// `PAD*`.
    pub fn as_pad(&self) -> Option<&'a Pad> {
        match self.item {
            AnyItem::Pad(x) => Some(x),
            _ => None,
        }
    }

    /// `FOOTPRINT*`.
    pub fn as_footprint(&self) -> Option<&'a Footprint> {
        match self.item {
            AnyItem::Footprint(x) => Some(x),
            _ => None,
        }
    }

    /// `PCB_TRACK*`: segment, arc or via.
    pub fn as_track(&self) -> Option<&'a Track> {
        match self.item {
            AnyItem::Track(x) => Some(x),
            _ => None,
        }
    }

    /// `PCB_VIA*`.
    pub fn as_via(&self) -> Option<&'a PcbVia> {
        self.as_track().and_then(Track::as_via)
    }

    /// `PCB_ARC*`.
    pub fn as_arc(&self) -> Option<&'a PcbArc> {
        self.as_track().and_then(Track::as_arc)
    }

    /// `ZONE*`.
    pub fn as_zone(&self) -> Option<&'a Zone> {
        match self.item {
            AnyItem::Zone(x) => Some(x),
            _ => None,
        }
    }

    /// `PCB_SHAPE*`: also the box of a textbox / table cell.
    pub fn as_shape(&self) -> Option<&'a PcbShape> {
        match self.item {
            AnyItem::Shape(x) => Some(x),
            AnyItem::Textbox(x) => Some(&x.shape),
            AnyItem::Tablecell(x) => Some(&x.textbox.shape),
            _ => None,
        }
    }

    /// `PCB_TEXT*`: also field and dimension text.
    pub fn as_text(&self) -> Option<&'a PcbText> {
        match self.item {
            AnyItem::Text(x) => Some(x),
            AnyItem::Field(x) => Some(&x.text),
            AnyItem::Dimension(x) => Some(&x.text),
            _ => None,
        }
    }

    /// `EDA_TEXT*` (`board-model.md` 6.2a): texts, fields, dimensions, textboxes, cells and the
    /// barcode's text.
    pub fn as_eda_text(&self) -> Option<&'a dyn EdaTextItem> {
        match self.item {
            AnyItem::Text(x) => Some(x),
            AnyItem::Field(x) => Some(&x.text),
            AnyItem::Dimension(x) => Some(&x.text),
            AnyItem::Textbox(x) => Some(x),
            AnyItem::Tablecell(x) => Some(&x.textbox),
            AnyItem::Barcode(x) => Some(&x.text),
            _ => None,
        }
    }

    /// `EDA_SHAPE*` (`board-model.md` 6.2a): shapes, textboxes, cells.
    pub fn as_eda_shape(&self) -> Option<&'a dyn EdaShapeItem> {
        match self.item {
            AnyItem::Shape(x) => Some(x),
            AnyItem::Textbox(x) => Some(x),
            AnyItem::Tablecell(x) => Some(&x.textbox),
            _ => None,
        }
    }

    /// `PCB_TEXTBOX*`: also table cell.
    pub fn as_textbox(&self) -> Option<&'a PcbTextbox> {
        match self.item {
            AnyItem::Textbox(x) => Some(x),
            AnyItem::Tablecell(x) => Some(&x.textbox),
            _ => None,
        }
    }

    /// `PCB_TABLE*`.
    pub fn as_table(&self) -> Option<&'a PcbTable> {
        match self.item {
            AnyItem::Table(x) => Some(x),
            _ => None,
        }
    }

    /// `PCB_DIMENSION_BASE*`.
    pub fn as_dimension(&self) -> Option<&'a PcbDimension> {
        match self.item {
            AnyItem::Dimension(x) => Some(x),
            _ => None,
        }
    }

    /// `EDA_GROUP*`: group, or a generator's group.
    pub fn as_group(&self) -> Option<&'a PcbGroup> {
        match self.item {
            AnyItem::Group(x) => Some(x),
            AnyItem::Generator(x) => Some(&x.group),
            _ => None,
        }
    }

    /// `NETINFO_ITEM*`.
    pub fn as_net(&self) -> Option<&'a NetinfoItem> {
        match self.item {
            AnyItem::Net(x) => Some(x),
            _ => None,
        }
    }

    /// `dynamic_cast<BOARD_CONNECTED_ITEM*>`.
    pub fn as_connected(&self) -> Option<&'a dyn BoardConnectedItem> {
        self.item.as_connected()
    }

    // ---- relations ----

    /// `GetParent()` as an item (`None` for the board, a detached value or a stale parent).
    pub fn parent(&self) -> Option<ItemRef<'a>> {
        self.ctx.item(self.base().parent.item()?)
    }

    /// `GetParentFootprint()` (`findParent( PCB_FOOTPRINT_T )`: walks the whole parent chain,
    /// e.g. through a table for a cell).
    pub fn parent_footprint(&self) -> Option<ItemRef<'a>> {
        let mut parent = self.parent();

        while let Some(p) = parent {
            if p.item.kind() == ItemKind::Footprint {
                return Some(p);
            }

            parent = p.parent();
        }

        None
    }

    /// Handle of [`ItemRef::parent_footprint`].
    pub fn parent_footprint_id(&self) -> Option<FootprintId> {
        self.parent_footprint()?.id()?.typed()
    }

    /// `GetParentGroup()`.
    pub fn parent_group(&self) -> Option<ItemRef<'a>> {
        self.ctx.item(self.base().group?)
    }

    /// `RunOnChildren` collected into a vector.
    pub fn children(&self, mode: RecurseMode) -> Vec<ItemRef<'a>> {
        let mut ids = Vec::new();
        self.as_dyn()
            .run_on_children(self.ctx, mode, &mut |child| ids.extend(child.id()));
        ids.into_iter().filter_map(|id| self.ctx.item(id)).collect()
    }

    /// True when the parent chain reaches the board (C++ `GetBoard() != nullptr`).
    pub fn has_board(&self) -> bool {
        match self.base().parent {
            ParentRef::None => false,
            ParentRef::Board => true,
            ParentRef::Item(_) => self.parent().is_some_and(|p| p.has_board()),
        }
    }

    // ---- BoardItem / BoardConnectedItem methods with the context bound ----

    /// `GetLayer()`.
    pub fn layer(&self) -> PcbLayerId {
        self.as_dyn().layer(self.ctx)
    }

    /// `GetLayerSet()`.
    pub fn layer_set(&self) -> Lset {
        self.as_dyn().layer_set(self.ctx)
    }

    /// `IsOnLayer()`.
    pub fn is_on_layer(&self, l: PcbLayerId) -> bool {
        self.as_dyn().is_on_layer(self.ctx, l)
    }

    /// `GetPosition()`.
    pub fn position(&self) -> Vector2I {
        self.as_dyn().position(self.ctx)
    }

    /// `GetBoundingBox()`.
    pub fn bounding_box(&self) -> Box2I {
        self.as_dyn().bounding_box(self.ctx)
    }

    /// `GetEffectiveShape()`.
    pub fn effective_shape(
        &self,
        layer: PcbLayerId,
        flash: Flashing,
        usage: DrcConstraintT,
    ) -> SharedShape {
        self.as_dyn().effective_shape(self.ctx, layer, flash, usage)
    }

    /// `GetEffectiveHoleShape()`.
    pub fn effective_hole_shape(
        &self,
        layer: PcbLayerId,
        usage: DrcConstraintT,
    ) -> Option<Arc<ShapeSegment>> {
        self.as_dyn().effective_hole_shape(self.ctx, layer, usage)
    }

    /// `TransformShapeToPolygon()`.
    pub fn transform_shape_to_polygon(
        &self,
        buf: &mut ShapePolySet,
        layer: PcbLayerId,
        clearance: i32,
        error: i32,
        error_loc: ErrorLoc,
        ignore_line_width: bool,
    ) {
        self.as_dyn().transform_shape_to_polygon(
            self.ctx,
            buf,
            layer,
            clearance,
            error,
            error_loc,
            ignore_line_width,
        )
    }

    /// `HasHole()`.
    pub fn has_hole(&self) -> bool {
        self.as_dyn().has_hole(self.ctx)
    }

    /// `IsLocked()`.
    pub fn is_locked(&self) -> bool {
        self.as_dyn().is_locked(self.ctx)
    }

    /// `IsTented()`.
    pub fn is_tented(&self, l: PcbLayerId) -> bool {
        self.as_dyn().is_tented(self.ctx, l)
    }

    /// `GetItemDescription()`.
    pub fn item_description(&self, units: &UnitsProvider<'_>, full: bool) -> String {
        self.as_dyn().item_description(self.ctx, units, full)
    }

    /// `BOARD_ITEM::GetMaxError()`: the board's value, `ARC_HIGH_DEF` without a board.
    pub fn max_error(&self) -> i32 {
        if self.has_board() {
            self.ctx.max_error()
        } else {
            ARC_HIGH_DEF
        }
    }

    /// `BOARD_ITEM::GetFlippedLayer()`.
    pub fn flipped_layer(&self, l: PcbLayerId) -> PcbLayerId {
        if self.has_board() {
            self.ctx.flip_layer(l)
        } else {
            kicad_core::layer_ids::flip_layer(l, 0)
        }
    }

    /// `BOARD_ITEM::BoardCopperLayerCount()`: 32 without a board.
    pub fn board_copper_layer_count(&self) -> i32 {
        if self.has_board() {
            self.ctx.copper_layer_count()
        } else {
            32
        }
    }

    /// `BOARD_ITEM::GetLayerName()`.
    pub fn layer_name(&self) -> String {
        crate::port_pending!("BOARD_ITEM::GetLayerName")
    }

    /// `BOARD_ITEM::GetFPRelativePosition()`.
    pub fn fp_relative_position(&self) -> Vector2I {
        crate::port_pending!("BOARD_ITEM::GetFPRelativePosition")
    }

    /// `IsConnected()`; false for non-connected kinds.
    pub fn is_connected(&self) -> bool {
        self.as_connected()
            .is_some_and(|c| c.is_connected(self.ctx))
    }

    /// `GetNetCode()`; `None` for non-connected kinds.
    pub fn net_code(&self) -> Option<NetCode> {
        self.as_connected().map(|c| c.net_code())
    }

    /// `GetNet()`.
    pub fn net(&self) -> Option<&'a NetinfoItem> {
        self.ctx.board.find_net(self.net_code()?)
    }

    /// `GetNetname()`.
    pub fn netname(&self) -> &'a str {
        crate::port_pending!("BOARD_CONNECTED_ITEM::GetNetname")
    }

    /// `GetEffectiveNetClass()`; `None` for non-connected kinds.
    pub fn effective_netclass(&self) -> Option<&'a Netclass> {
        let ctx: &'a BoardCtx<'a> = self.ctx;
        self.as_connected().map(|c| c.effective_netclass(ctx))
    }

    /// `GetOwnClearance( aLayer )`; 0 for non-connected kinds.
    pub fn own_clearance(&self, layer: PcbLayerId) -> i32 {
        self.as_connected()
            .map_or(0, |c| c.own_clearance(self.ctx, layer, false).0)
    }

    /// `GetOwnClearance( aLayer, &source )`.
    pub fn own_clearance_with_source(&self, layer: PcbLayerId) -> (i32, String) {
        self.as_connected().map_or((0, String::new()), |c| {
            let (clearance, source) = c.own_clearance(self.ctx, layer, true);
            (clearance, source.unwrap_or_default())
        })
    }

    /// Replaces toggling the `HOLE_PROXY` flag on the tested item (drc_test_provider_disallow).
    pub fn as_hole_proxy(self) -> ItemRef<'a> {
        ItemRef {
            hole_proxy: true,
            ..self
        }
    }

    /// True for a reference made by [`ItemRef::as_hole_proxy`].
    pub fn is_hole_proxy(&self) -> bool {
        self.hole_proxy
    }
}
