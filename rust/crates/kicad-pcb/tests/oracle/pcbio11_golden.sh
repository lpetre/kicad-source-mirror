#!/bin/bash
# PCBIO-11 differential oracle (legacy net classes, net chains, variants, embedded files).
# Every board is copied alone into a fresh scratch directory (no project files) first.
#  1. byte level: the hand-made boards tests/data/pcbio11/*.kicad_pcb are re-saved with the
#     reference `kicad-cli pcb upgrade --force` to tests/golden/pcbio11/<name>.kicad_pcb (O1);
#     the warnings / errors the reference prints go to <name>.log.txt with the scratch path
#     replaced by <file> (a board that fails to load has a log and no O1);
#  2. item level: `pcb-dump board --no-init --sections board` of the hand-made boards and of
#     every corpus board with a legacy `(net_class ..)` section (qa/data), filtered to the
#     net class, pattern and net lines -> tests/golden/pcbio11/<name>.dump.txt and
#     tests/golden/pcbio11_corpus_netclass.txt;
#  3. corpus byte level: every board of qa/data/pcbnew and demos (< 20 MB) containing
#     "(net_chains", "(variants" or "(embedded_files" is re-saved and each top-level
#     (variants ..), (net_chains ..), (embedded_fonts ..) and (embedded_files ..) block of the
#     result is recorded in tests/golden/pcbio11_corpus_sections.txt as
#       path|keyword|lines=N|fnv(block)
#     (FNV-1a 64 of the block lines, from "\t(<keyword>" to its closing "\t)" line).
# Replayed by the Rust tests in src/io/parser/netclass_embedded.rs (the block extraction is
# mirrored there).
#
# Usage: tests/oracle/pcbio11_golden.sh   (run from rust/crates/kicad-pcb; ~3 minutes, alone:
# it runs the reference build on RoyalBlue54L-Feather)
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/../../../.." && pwd)
cli=${KICAD_ORACLE_CLI:-/home/user/kicad-oracle/bin/kicad-cli}
dump=${PCB_DUMP:-/home/user/kicad-oracle/bin/pcb-dump}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
export KICAD_ORACLE_HOME=$scratch/home
tool=$scratch/blocks.py
filter='^file\||ds\.netclass|netclass_pattern|\|net\.[0-9]+\.|effective_netclass'

resave() {   # resave <in> <out> [<log>]
    local d=$scratch/b
    rm -rf "$d"; mkdir -p "$d"
    cp "$1" "$d/board.kicad_pcb"
    local ok=0
    timeout 300 nice -n 10 "$cli" pcb upgrade --force "$d/board.kicad_pcb" > "$d/log" 2>&1 \
        && grep -q "Successfully saved" "$d/log" && cp "$d/board.kicad_pcb" "$2" || ok=1
    if [ $# -ge 3 ]; then
        grep -v "schema file\|Successfully saved" "$d/log" \
            | sed -e "s|$d/board.kicad_pcb|<file>|g" -e 's/^[0-9:]*: //' > "$3" || true
    fi
    return $ok
}

cat > "$tool" <<'PY'
import sys
def fnv(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return '%016x' % h
path = sys.argv[2]
lines = open(sys.argv[1], 'rb').read().splitlines(keepends=True)
found = 0
i = 0
for kw in (b'variants', b'net_chains', b'embedded_fonts', b'embedded_files'):
    for i, l in enumerate(lines):
        if not l.startswith(b'\t(' + kw):
            continue
        j = i
        if not l.rstrip(b'\n').endswith(b')'):
            while lines[j] != b'\t)\n':
                j += 1
        block = lines[i:j + 1]
        print('%s|%s|lines=%d|%s' % (path, kw.decode(), len(block), fnv(b''.join(block))))
        found += 1
if not found:
    print('%s|none' % path)
PY

mkdir -p "$here/golden/pcbio11"
for f in "$here"/data/pcbio11/*.kicad_pcb; do
    n=$(basename "$f" .kicad_pcb)
    rm -f "$here/golden/pcbio11/$n.kicad_pcb"
    resave "$f" "$here/golden/pcbio11/$n.kicad_pcb" "$here/golden/pcbio11/$n.log.txt" || true
    mkdir -p "$scratch/d"; cp "$f" "$scratch/d/$n.kicad_pcb"
    "$dump" board --no-init --sections board "$scratch/d/$n.kicad_pcb" 2>/dev/null \
        | grep -E "$filter" > "$here/golden/pcbio11/$n.dump.txt" || true
    echo "$n"
done

cd "$root"
out=$here/golden/pcbio11_corpus_netclass.txt
echo "# generated by tests/oracle/pcbio11_golden.sh" > "$out"
grep -l -r --include='*.kicad_pcb' '(net_class ' qa/data demos | LC_ALL=C sort | while read -r f; do
    rm -rf "$scratch/d"; mkdir -p "$scratch/d"; cp "$f" "$scratch/d/"
    echo "path|$f" >> "$out"
    "$dump" board --no-init --sections board "$scratch/d/$(basename "$f")" 2>/dev/null \
        | grep -E "$filter" >> "$out" || echo "error|$f" >> "$out"
done
wc -l "$out"

out=$here/golden/pcbio11_corpus_sections.txt
echo "# generated by tests/oracle/pcbio11_golden.sh" > "$out"
grep -l -r --include='*.kicad_pcb' -e '(net_chains' -e '(variants' -e '(embedded_files' \
    qa/data/pcbnew demos | LC_ALL=C sort | while read -r f; do
    if [ "$(stat -c %s "$f")" -ge 20000000 ]; then
        continue
    fi
    if resave "$f" "$scratch/o.kicad_pcb"; then
        python3 -I "$tool" "$scratch/o.kicad_pcb" "$f" >> "$out"
    else
        echo "$f|error" >> "$out"
    fi
done
wc -l "$out"
