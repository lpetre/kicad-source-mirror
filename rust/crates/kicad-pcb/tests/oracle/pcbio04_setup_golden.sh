#!/bin/bash
# PCBIO-04 corpus oracle: re-save every board of qa/data/pcbnew and demos below 2 MB with the
# reference `kicad-cli pcb upgrade --force` (each board copied alone into a fresh scratch
# directory: no project files) and record the FNV-1a 64 hash of the top-level (setup ..)
# section of the result: the lines from "\t(setup\n" to the next "\t)\n", both included.
# Output: tests/golden/pcbio04_setup_corpus.txt, lines "path|hash" (path relative to the KiCad
# source root) or "path|error" when the reference build does not save the board.
# With SETUP_DUMP_DIR set, the setup sections themselves are also written there (one file per
# board, '/' replaced by '__') for diffing; they are not committed.
# Replayed by the Rust test `io::parser::setup::tests::oracle_corpus_setup`.
#
# Usage: tests/oracle/pcbio04_setup_golden.sh   (~5 minutes)
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/../../../.." && pwd)
cli=${KICAD_ORACLE_CLI:-/home/user/kicad-oracle/bin/kicad-cli}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
export KICAD_ORACLE_HOME=$scratch/home
out=$here/golden/pcbio04_setup_corpus.txt
tool=$scratch/setup.py

cat > "$tool" <<'PY'
import sys
def fnv(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return '%016x' % h
lines = open(sys.argv[1], 'rb').read().splitlines(keepends=True)
s = b''
i = 0
while i < len(lines) and lines[i] != b'\t(setup\n':
    i += 1
while i < len(lines):
    s += lines[i]
    if lines[i] == b'\t)\n':
        break
    i += 1
if len(sys.argv) > 2:
    open(sys.argv[2], 'wb').write(s)
print(fnv(s))
PY

echo "# generated by tests/oracle/pcbio04_setup_golden.sh" > "$out"
cd "$root"
find qa/data/pcbnew demos -name '*.kicad_pcb' -size -2M | LC_ALL=C sort | while read -r f; do
    d=$scratch/b
    rm -rf "$d"; mkdir -p "$d"
    cp "$f" "$d/board.kicad_pcb"
    dump=()
    if [ -n "${SETUP_DUMP_DIR:-}" ]; then
        dump=("$SETUP_DUMP_DIR/${f//\//__}.setup")
    fi
    if timeout 120 nice -n 10 "$cli" pcb upgrade --force "$d/board.kicad_pcb" > "$d/log" 2>&1 \
        && grep -q "Successfully saved" "$d/log"; then
        echo "$f|$(python3 -I "$tool" "$d/board.kicad_pcb" "${dump[@]}")" >> "$out"
    else
        echo "$f|error" >> "$out"
    fi
done
rm -rf "$scratch/b"
wc -l "$out"
