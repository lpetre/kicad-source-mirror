#!/bin/sh
# Regenerate tests/golden/m20_footprints.txt (package M20): the footprint-level geometry
# (bounding boxes, hulls, courtyards, area) and the save order of the footprint pads / drawings / zones of tests/data/m20/m20_footprints.kicad_pcb as the
# reference pcb-dump prints it. Runs on a scratch copy of the board (pcb-dump writes nothing,
# but the oracle rules ask for copies). Small board: no build, one reference process.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
dump=${PCB_DUMP:-/home/user/kicad-oracle/bin/pcb-dump}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
cp "$here/data/m20/m20_footprints.kicad_pcb" "$scratch/"
out="$here/golden/m20_footprints.txt"
{
    echo "# pcb-dump board --sections bbox,footprint tests/data/m20/m20_footprints.kicad_pcb (footprint-level geometry; generated by tests/oracle/m20_footprint_golden.sh)"
    "$dump" board --sections bbox,footprint "$scratch/m20_footprints.kicad_pcb" 2>/dev/null |
        grep -E '^(bbox|footprint)\|[a-d]{8}-0000-4000-8000-000000000000\|(bbox|bbox_with_text|bbox_without_text|fp_pads_local_bbox|bounding_hull|layer_bbox\.F_Cu|layer_bbox\.B_Cu|courtyard\.F|courtyard\.B|hull\.F_Cu|hull\.B_Cu|area)='
    "$dump" board --sections order "$scratch/m20_footprints.kicad_pcb" 2>/dev/null |
        grep -E '^order\|board\|fp\..*\.(pads|drawings|zones)=\[[^]]'
} > "$out"
wc -l "$out"
