#!/usr/bin/env python3
# Package M4: generates tests/data/net_settings/corpus_scenarios.txt from the corpus. For every
# .kicad_pro under qa/ and demos/ with netclass patterns: one `rx` line per distinct pattern
# (does the anchored regex compile), and, when a .kicad_pcb sits next to it, a scenario with its
# netclass names / priorities (fields left unset), patterns and label assignments, querying the
# effective netclass name (`qn`) of up to 300 of the board's net names. Fields are separated by
# tabs (patterns may contain '|'). Usage: tests/oracle/net_settings_corpus.py  (any directory)
import glob, json, os, re

here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
root = os.path.abspath(os.path.join(here, "..", "..", ".."))
out_path = os.path.join(here, "tests", "data", "net_settings", "corpus_scenarios.txt")
pros = sorted(glob.glob(os.path.join(root, "qa", "**", "*.kicad_pro"), recursive=True)
              + glob.glob(os.path.join(root, "demos", "**", "*.kicad_pro"), recursive=True))
patterns_seen, lines = set(), []
net_re = re.compile(r'^\s*\(net (\d+) "((?:[^"\\]|\\.)*)"\)\s*$')

def ok(s):
    return "\t" not in s and "\n" not in s and "\r" not in s

for pro in pros:
    try:
        j = json.load(open(pro, encoding="utf-8"))
    except Exception:
        continue
    ns = j.get("net_settings") or {}
    pats = [p for p in (ns.get("netclass_patterns") or []) if isinstance(p, dict)]
    if not pats:
        continue
    for p in pats:
        pat = p.get("pattern", "")
        if pat not in patterns_seen and ok(pat):
            patterns_seen.add(pat)
            lines.append("rx\t" + pat)
    pcb = pro[:-len(".kicad_pro")] + ".kicad_pcb"
    if not os.path.exists(pcb):
        continue
    nets = []
    for l in open(pcb, encoding="utf-8", errors="replace"):
        m = net_re.match(l)
        if m and m.group(2):
            name = m.group(2).replace('\\"', '"').replace("\\\\", "\\")
            if ok(name) and name not in nets:
                nets.append(name)
    if not nets:
        continue
    lines.append("reset\t" + os.path.relpath(pro, root))
    for c in ns.get("classes") or []:
        name, prio = c.get("name", ""), c.get("priority", -1)
        if name and name != "Default" and ok(name) and isinstance(prio, int):
            lines.append("\t".join(["class", name, str(prio)] + ["~"] * 14 + [""]))
    for p in pats:
        if ok(p.get("pattern", "")) and ok(p.get("netclass", "")):
            lines.append("\t".join(["pattern", p.get("pattern", ""), p.get("netclass", "")]))
    labels = ns.get("netclass_assignments") or {}
    if isinstance(labels, dict):
        for net, cls in sorted(labels.items()):
            cls = [cls] if isinstance(cls, str) else list(cls or [])
            if cls and ok(net) and all(ok(c) and "," not in c for c in cls):
                lines.append("\t".join(["label", net, ",".join(cls)]))
    for n in nets[:300]:
        lines.append("qn\t" + n)

with open(out_path, "w", encoding="utf-8") as f:
    f.write("# Generated by tests/oracle/net_settings_corpus.py; do not edit.\n")
    f.write("\n".join(lines) + "\n")
print(out_path, len(lines))
