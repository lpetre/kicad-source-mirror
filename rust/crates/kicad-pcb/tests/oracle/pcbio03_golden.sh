# PCBIO-03 differential oracle (tracks, vias, arcs, board graphic shapes), two parts, both with
# the reference `kicad-cli pcb upgrade --force` of a board copied alone into a fresh scratch
# directory (no project files):
#  1. the hand-made boards tests/data/pcbio03/*.kicad_pcb are re-saved to
#     tests/golden/pcbio03/<name>.kicad_pcb (O1) and O1 once more to <name>_o2.kicad_pcb when
#     that differs (all four are fixed points today);
#  2. every corpus board (qa/data/pcbnew and demos) re-saved by the io-corpus harness
#     (rust/tools/io-corpus/run.sh, cache rust/target/io-corpus/boards/<flat>/o1.kicad_pcb, which
#     is exactly such a re-save; run it first) is reduced to its top-level (one tab) blocks
#     "segment", "arc", "via" (kind "tracks") and "gr_line", "gr_rect", "gr_circle", "gr_arc",
#     "gr_poly", "gr_curve", "gr_ellipse", "gr_ellipse_arc" (kind "graphics"), recorded in
#     tests/golden/pcbio03_corpus.txt as
#       path|kind|count|fnv(blocks in file order)|fnv(blocks sorted bytewise)
#     (FNV-1a 64; a block is the lines from its keyword to its closing ")" line).
# Replayed by tests/pcbio03_tracks_shapes.rs (the block extraction is mirrored there).
#
# Usage: tests/oracle/pcbio03_golden.sh   (run from rust/crates/kicad-pcb)
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
rust=$(cd "$here/../../.." && pwd)
cli=${KICAD_ORACLE_CLI:-/home/user/kicad-oracle/bin/kicad-cli}
cache=${IO_CORPUS_DIR:-$rust/target/io-corpus}/boards
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
export KICAD_ORACLE_HOME=$scratch/home

resave() {   # resave <in> <out>
    local d=$scratch/b
    rm -rf "$d"; mkdir -p "$d"
    cp "$1" "$d/board.kicad_pcb"
    timeout 300 nice -n 10 "$cli" pcb upgrade --force "$d/board.kicad_pcb" > "$d/log" 2>&1 \
        && grep -q "Successfully saved" "$d/log" && cp "$d/board.kicad_pcb" "$2"
}

mkdir -p "$here/golden/pcbio03"
for f in "$here"/data/pcbio03/*.kicad_pcb; do
    n=$(basename "$f" .kicad_pcb)
    o1=$here/golden/pcbio03/$n.kicad_pcb
    resave "$f" "$o1"
    resave "$o1" "$scratch/o2.kicad_pcb"
    if cmp -s "$o1" "$scratch/o2.kicad_pcb"; then
        rm -f "$here/golden/pcbio03/${n}_o2.kicad_pcb"
    else
        cp "$scratch/o2.kicad_pcb" "$here/golden/pcbio03/${n}_o2.kicad_pcb"
    fi
done

python3 -I - "$cache" > "$here/golden/pcbio03_corpus.txt" <<'PY'
import os, sys
TRACKS = (b'segment', b'arc', b'via')
GRAPHICS = (b'gr_line', b'gr_rect', b'gr_circle', b'gr_arc', b'gr_poly', b'gr_curve',
            b'gr_ellipse', b'gr_ellipse_arc')
def fnv(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return '%016x' % h
def blocks(data):
    out = {'tracks': [], 'graphics': []}
    lines = data.splitlines(keepends=True)
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith(b'\t(') and not l.startswith(b'\t\t'):
            word = l[2:].split(b' ')[0].split(b'\n')[0].rstrip(b')')
            kind = 'tracks' if word in TRACKS else 'graphics' if word in GRAPHICS else None
            j = i
            if not l.rstrip(b'\n').endswith(b')') or l.count(b'(') != l.count(b')'):
                while j < len(lines) and lines[j] != b'\t)\n':
                    j += 1
            if kind:
                out[kind].append(b''.join(lines[i:j + 1]))
            i = j + 1
        else:
            i += 1
    return out
cache = sys.argv[1]
print('# generated by tests/oracle/pcbio03_golden.sh')
for flat in sorted(os.listdir(cache)):
    d = os.path.join(cache, flat)
    meta = open(os.path.join(d, 'meta')).read()
    if 'saved' not in meta:
        continue
    path = flat.replace('__', '/')
    b = blocks(open(os.path.join(d, 'o1.kicad_pcb'), 'rb').read())
    for kind in ('tracks', 'graphics'):
        v = b[kind]
        print('%s|%s|%d|%s|%s' % (path, kind, len(v), fnv(b''.join(v)), fnv(b''.join(sorted(v)))))
PY
