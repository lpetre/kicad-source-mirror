# PCBIO-08 differential oracle (board zones), both parts with the reference
# `kicad-cli pcb upgrade --force` of a board copied alone into a fresh scratch directory:
#  1. the hand-made boards tests/data/pcbio08/*.kicad_pcb are re-saved to
#     tests/golden/pcbio08/<name>.kicad_pcb (O1);
#  2. every corpus board re-saved by the io-corpus harness (rust/tools/io-corpus/run.sh, cache
#     rust/target/io-corpus/boards/<flat>/o1.kicad_pcb, exactly such a re-save; run it first)
#     is reduced to its top-level (one tab) "zone" blocks, recorded in
#     tests/golden/pcbio08_corpus.txt as
#       path|count|fnv(blocks in file order)|fnv(blocks sorted bytewise)|fnv(masked, sorted)
#     (FNV-1a 64; a block is the lines from "\t(zone" to its closing "\t)" line; "masked":
#     every "(uuid ...)" line whose UUID does not occur in the original board file is replaced
#     by "(uuid masked)", since zones without a UUID in the file get a random one).
# Replayed by tests/pcbio08_zones.rs (the block extraction is mirrored there).
#
# Usage: tests/oracle/pcbio08_golden.sh   (run from anywhere)
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
rust=$(cd "$here/../../.." && pwd)
cli=${KICAD_ORACLE_CLI:-/home/user/kicad-oracle/bin/kicad-cli}
cache=${IO_CORPUS_DIR:-$rust/target/io-corpus}/boards
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
export KICAD_ORACLE_HOME=$scratch/home

mkdir -p "$here/golden/pcbio08"
for f in "$here"/data/pcbio08/*.kicad_pcb; do
    d=$scratch/b
    rm -rf "$d"; mkdir -p "$d"
    cp "$f" "$d/board.kicad_pcb"
    timeout 300 nice -n 10 "$cli" pcb upgrade --force "$d/board.kicad_pcb" > "$d/log" 2>&1
    grep -q "Successfully saved" "$d/log"
    cp "$d/board.kicad_pcb" "$here/golden/pcbio08/$(basename "$f")"
done

python3 -I - "$cache" "$rust/.." > "$here/golden/pcbio08_corpus.txt" <<'PY'
import os, sys
def fnv(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return '%016x' % h
def zones(data):
    out, cur = [], None
    for l in data.splitlines(keepends=True):
        if cur is None:
            if l.startswith(b'\t(zone') and l.rstrip(b'\n') in (b'\t(zone', b'\t(zone)'):
                cur = [l]
                if l.rstrip(b'\n') == b'\t(zone)':
                    out.append(l); cur = None
        else:
            cur.append(l)
            if l == b'\t)\n':
                out.append(b''.join(cur)); cur = None
    return out
def masked(v, original):
    out = []
    for b in v:
        lines = []
        for l in b.splitlines(keepends=True):
            t = l.strip()
            if t.startswith(b'(uuid "') and t[7:-2] not in original:
                l = l[:len(l) - len(l.lstrip())] + b'(uuid masked)\n'
            lines.append(l)
        out.append(b''.join(lines))
    return sorted(out)
cache, root = sys.argv[1], sys.argv[2]
print('# generated by tests/oracle/pcbio08_golden.sh')
for flat in sorted(os.listdir(cache)):
    d = os.path.join(cache, flat)
    if 'saved' not in open(os.path.join(d, 'meta')).read():
        continue
    v = zones(open(os.path.join(d, 'o1.kicad_pcb'), 'rb').read())
    if v:
        path = flat.replace('__', '/')
        original = open(os.path.join(root, path), 'rb').read()
        print('%s|%d|%s|%s|%s' % (path, len(v), fnv(b''.join(v)), fnv(b''.join(sorted(v))),
                                  fnv(b''.join(masked(v, original)))))
PY
