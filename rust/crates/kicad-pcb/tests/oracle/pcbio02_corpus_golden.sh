#!/bin/bash
# PCBIO-02 corpus oracle: re-save every board of qa/data/pcbnew and demos below 2 MB with the
# reference `kicad-cli pcb upgrade --force` (each board copied alone into a fresh scratch
# directory: no project files) and record the FNV-1a 64 hashes of the three skeleton regions
# of the result (see skeleton_regions() in src/io/writer/tests.rs, same definition below):
#   A = everything from the start to the end of the top-level (layers ..) block (header,
#   general, paper, title block, layers), B = the top-level (property ..) / (variants ..)
#   blocks right after it and after the (setup ..) block (skipped if present), C = the
#   "\t(embedded_fonts ..)" line.
# Output: tests/golden/pcbio02_corpus.txt, lines "path|hashA|hashB|hashC" (path relative to the
# KiCad source root) or "path|error" when the reference build does not save the board.
# Replayed by the Rust test `io::writer::tests::oracle_corpus_skeleton`.
#
# Usage: tests/oracle/pcbio02_corpus_golden.sh   (~5 minutes)
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/../../../.." && pwd)
cli=${KICAD_ORACLE_CLI:-/home/user/kicad-oracle/bin/kicad-cli}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
export KICAD_ORACLE_HOME=$scratch/home
out=$here/golden/pcbio02_corpus.txt
tool=$scratch/regions.py

cat > "$tool" <<'PY'
import sys
def fnv(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return '%016x' % h
data = open(sys.argv[1], 'rb').read()
lines = data.splitlines(keepends=True)
a, b, c = b'', b'', b''
i = 0
while i < len(lines) and lines[i] != b'\t(layers\n':
    a += lines[i]; i += 1
while i < len(lines) and lines[i] != b'\t)\n':
    a += lines[i]; i += 1
if i < len(lines):
    a += lines[i]; i += 1
if i < len(lines) and lines[i] == b'\t(setup\n':
    while i < len(lines) and lines[i] != b'\t)\n':
        i += 1
    i += 1
while i < len(lines):
    l = lines[i]
    if l.startswith(b'\t(property '):
        b += l; i += 1
    elif l == b'\t(variants\n':
        while i < len(lines) and lines[i] != b'\t)\n':
            b += lines[i]; i += 1
        if i < len(lines):
            b += lines[i]
        i += 1
    else:
        break
for l in lines:
    if l.startswith(b'\t(embedded_fonts '):
        c += l
print('%s|%s|%s' % (fnv(a), fnv(b), fnv(c)))
PY

echo "# generated by tests/oracle/pcbio02_corpus_golden.sh" > "$out"
cd "$root"
find qa/data/pcbnew demos -name '*.kicad_pcb' -size -2M | LC_ALL=C sort | while read -r f; do
    d=$scratch/b
    rm -rf "$d"; mkdir -p "$d"
    cp "$f" "$d/board.kicad_pcb"
    if timeout 120 nice -n 10 "$cli" pcb upgrade --force "$d/board.kicad_pcb" > "$d/log" 2>&1 \
        && grep -q "Successfully saved" "$d/log"; then
        echo "$f|$(python3 -I "$tool" "$d/board.kicad_pcb")" >> "$out"
    else
        echo "$f|error" >> "$out"
    fi
done
rm -rf "$scratch/b"
wc -l "$out"
