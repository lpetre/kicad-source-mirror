//! Package M8 differential test: replays `tests/golden/m8_shapes.txt` (reference `pcb-dump
//! board --sections shape` of `tests/oracle/m8_shapes.kicad_pcb`, regenerated by
//! `tests/oracle/m8_shapes_golden.sh`).
//!
//! The board parser does not load graphic shapes yet (PCBIO-03), so each shape is rebuilt from
//! its dumped members (the line endings, which the dump does not print, from the table below,
//! copied from the board file) on a host that behaves like a board-level `PCB_SHAPE`
//! (`GetWidth` clamps at 0, `getMaxError` = board maximum error, no hatching knockouts: no
//! hatched shape of the board overlaps another item of its layer). Checked, bit for bit
//! (FNV-1a of the dump text): `shape.<L>` = `SHAPE_COMPOUND( MakeEffectiveShapesWithLineEndings(
//! GetEffectiveWidth() ) )`, `tpoly.<L>.<combo>` = `EDA_SHAPE::TransformShapeToPolygon` and
//! `hatching` = `GetHatching()`.

#![cfg(feature = "dump")]

use std::collections::BTreeMap;

use kicad_geom::geometry::approximation::ErrorLoc;
use kicad_geom::{EdaAngle, ShapeCompound, ShapeLineChain, ShapePolySet, Vector2I};
use kicad_pcb::board::Board;
use kicad_pcb::ctx::BoardCtx;
use kicad_pcb::dump::fnv1a64;
use kicad_pcb::dump::format::{v_polyset, v_shape};
use kicad_pcb::eda_shape::shapes::make_effective_shapes_with_line_endings;
use kicad_pcb::eda_shape::{ArcMid, EdaShape, EdaShapeExt, FillT, ShapeT};
use kicad_pcb::line_ending::{LineEnding, LineEndingStyle};
use kicad_pcb::traits::EdaShapeItem;

/// A board-level `PCB_SHAPE` as far as the `EDA_SHAPE` virtuals go.
struct BoardShape(EdaShape);

impl EdaShapeItem for BoardShape {
    fn eda_shape(&self) -> &EdaShape {
        &self.0
    }

    fn eda_shape_mut(&mut self) -> &mut EdaShape {
        &mut self.0
    }

    /// `PCB_SHAPE::GetWidth()` outside a footprint.
    fn width(&self, _ctx: &BoardCtx<'_>) -> i32 {
        self.0.stroke.width().max(0)
    }

    /// `PCB_SHAPE::getMaxError()`: `GetMaxError()` of the board.
    fn shape_max_error(&self, ctx: &BoardCtx<'_>) -> i32 {
        ctx.max_error()
    }
}

const MM: f64 = 1_000_000.0;

fn mm(v: f64) -> i32 {
    (v * MM).round() as i32
}

fn ending(style: LineEndingStyle, length: f64, width: f64, stroke: f64) -> LineEnding {
    LineEnding::new(style, mm(length), mm(width), mm(stroke))
}

/// The line endings of `m8_shapes.kicad_pcb`, by uuid ordinal: (start, end).
fn endings(ordinal: u32) -> (LineEnding, LineEnding) {
    use LineEndingStyle::*;
    let none = LineEnding::default();

    match ordinal {
        2 => (ending(Circle, 1.0, 1.0, 0.0), ending(Arrow, 1.5, 1.2, 0.0)),
        3 => (
            ending(ArrowOpen, 1.5, 1.5, 0.2),
            ending(Square, 1.0, 1.0, 0.1),
        ),
        4 => (ending(Arrow, 1.0, 1.0, 0.0), ending(Arrow, 1.0, 1.0, 0.0)),
        18 => (ending(Arrow, 1.2, 1.0, 0.0), ending(Square, 0.8, 0.8, 0.0)),
        19 => (none, ending(ArrowOpen, 1.2, 1.2, 0.0)),
        26 => (ending(Arrow, 1.5, 1.0, 0.0), ending(Circle, 1.0, 1.0, 0.0)),
        27 => (
            ending(ArrowOpen, 1.4, 1.2, 0.0),
            ending(ArrowOpen, 1.4, 1.2, 0.15),
        ),
        32 => (none, ending(Arrow, 1.2, 1.0, 0.0)),
        _ => (none.clone(), none),
    }
}

fn pt(s: &str) -> Vector2I {
    let (x, y) = s.split_once(',').unwrap();
    Vector2I::new(x.parse().unwrap(), y.parse().unwrap())
}

fn pts(s: &str) -> Vec<Vector2I> {
    s.trim_start_matches('[')
        .trim_end_matches(']')
        .split_whitespace()
        .map(pt)
        .collect()
}

/// Parse a dumped polygon set without holes or arcs (`P(n {C(closed w=0 n=k [..])} ..)`).
fn polyset(s: &str) -> ShapePolySet {
    let mut set = ShapePolySet::new();

    for part in s.split("{C(").skip(1) {
        let closed = part.starts_with("closed");
        let open = part.find('[').unwrap();
        let close = part.find(']').unwrap();
        let chain = ShapeLineChain::from_points(&pts(&part[open..=close]), closed);
        set.add_outline(&chain);
    }

    set
}

fn shape_t(s: &str) -> ShapeT {
    match s {
        "SEGMENT" => ShapeT::Segment,
        "RECTANGLE" => ShapeT::Rectangle,
        "ARC" => ShapeT::Arc,
        "CIRCLE" => ShapeT::Circle,
        "POLY" => ShapeT::Poly,
        "BEZIER" => ShapeT::Bezier,
        "ELLIPSE" => ShapeT::Ellipse,
        "ELLIPSE_ARC" => ShapeT::EllipseArc,
        _ => panic!("shape {s}"),
    }
}

fn fill_t(s: &str) -> FillT {
    match s {
        "NO_FILL" => FillT::NoFill,
        "FILLED_SHAPE" => FillT::FilledShape,
        "HATCH" => FillT::Hatch,
        "REVERSE_HATCH" => FillT::ReverseHatch,
        "CROSS_HATCH" => FillT::CrossHatch,
        _ => panic!("fill {s}"),
    }
}

fn hash(s: &str) -> String {
    format!("#{:016x}", fnv1a64(s.as_bytes()))
}

/// Rebuild the shape from its dumped members (the stored values, so no setter maths).
fn rebuild(key: &str, f: &BTreeMap<String, String>) -> EdaShape {
    let g = |name: &str| f.get(name).unwrap_or_else(|| panic!("{key}: {name}"));
    let mut es = EdaShape::new(shape_t(g("shape")), 0, fill_t(g("fill")));

    es.stroke.set_width(g("width").parse().unwrap());
    es.start = pt(g("start"));
    es.end = pt(g("end"));

    match es.shape {
        ShapeT::Arc => {
            es.arc_center = pt(g("center"));
            // The loader's SetArcGeometry keeps the file's mid point (GetArcMid returns it
            // while start, end and centre are unchanged).
            es.arc_mid_data = ArcMid {
                mid: pt(g("mid")),
                start: es.start,
                end: es.end,
                center: es.arc_center,
            };
        }
        ShapeT::Rectangle => es.corner_radius = g("corner_radius").parse().unwrap(),
        ShapeT::Poly => es.poly = polyset(g("poly")),
        ShapeT::Bezier => {
            es.bezier_c1 = pt(g("bezier_c1"));
            es.bezier_c2 = pt(g("bezier_c2"));
            es.bezier_points = pts(g("bezier_points"));
        }
        ShapeT::Ellipse | ShapeT::EllipseArc => {
            let angle = |n: &str| EdaAngle::from_degrees(g(n).parse::<f64>().unwrap());
            es.ellipse.center = pt(g("ellipse_center"));
            es.ellipse.major_radius = g("ellipse_major").parse().unwrap();
            es.ellipse.minor_radius = g("ellipse_minor").parse().unwrap();
            es.ellipse.rotation = angle("ellipse_rotation");
            es.ellipse.start_angle = angle("ellipse_start");
            es.ellipse.end_angle = angle("ellipse_end");
        }
        _ => {}
    }

    let ordinal: u32 = key.rsplit('-').next().unwrap().parse().unwrap();
    let (start_ending, end_ending) = endings(ordinal);
    es.start_ending = start_ending;
    es.end_ending = end_ending;

    es
}

#[test]
fn m8_shapes_match_reference_dump() {
    let golden = include_str!("golden/m8_shapes.txt");
    let mut items: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();

    for line in golden.lines() {
        let mut parts = line.splitn(3, '|');
        let (_section, key, rest) = (
            parts.next().unwrap(),
            parts.next().unwrap(),
            parts.next().unwrap(),
        );
        let (field, value) = rest.split_once('=').unwrap();

        if !items.contains_key(key) {
            order.push(key.to_string());
        }

        items
            .entry(key.to_string())
            .or_default()
            .insert(field.to_string(), value.to_string());
    }

    let board = Board::default();
    let ctx = BoardCtx::bare(&board);
    let mut checked = 0;
    let mut failures: Vec<String> = Vec::new();

    for key in &order {
        let f = &items[key];
        let host = BoardShape(rebuild(key, f));

        // Sanity: the members the reference derives from the rebuilt data.
        assert_eq!(
            host.effective_width(&ctx).to_string(),
            f["effective_width"],
            "{key}"
        );
        assert_eq!(
            host.hatch_line_spacing(&ctx).to_string(),
            f["hatch_line_spacing"],
            "{key}"
        );

        for (field, expected) in f {
            let actual = if field.starts_with("shape.") {
                let compound = ShapeCompound::from_shapes(make_effective_shapes_with_line_endings(
                    &host,
                    &ctx,
                    host.effective_width(&ctx),
                ));
                v_shape(Some(&compound))
            } else if let Some(rest) = field.strip_prefix("tpoly.") {
                let combo = rest.rsplit('.').next().unwrap();
                let (clearance, error, error_loc) = match combo {
                    "c0_e5000_in" => (0, 5000, ErrorLoc::Inside),
                    "c0_e1000_out" => (0, 1000, ErrorLoc::Outside),
                    "c100000_e5000_out" => (100_000, 5000, ErrorLoc::Outside),
                    _ => panic!("combo {combo}"),
                };
                let mut buffer = ShapePolySet::new();
                host.shape_transform_to_polygon(
                    &ctx,
                    &mut buffer,
                    clearance,
                    error,
                    error_loc,
                    false,
                    false,
                );
                v_polyset(&buffer)
            } else if field == "hatching" {
                v_polyset(&host.hatching(&ctx))
            } else {
                continue;
            };

            checked += 1;

            if hash(&actual) != *expected {
                failures.push(format!(
                    "{key}|{field}: {}",
                    &actual[..actual.len().min(300)]
                ));
            }
        }
    }

    // 32 shapes x (1 effective shape + 3 polygon combos) + 8 hatchings.
    assert_eq!(checked, 136, "geometry fields checked");
    assert!(
        failures.is_empty(),
        "{} of {checked} mismatches:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
