//! The corpus scoreboard (`rust/target/io-corpus/scoreboard.md`) and the per-board report of
//! `run.sh --board` (new code, test support).

#![allow(dead_code)]

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::resave::{Evaluation, Status, pending_summary};

/// The result of one corpus board.
#[derive(Clone, Debug)]
pub struct BoardResult {
    /// Corpus name (path relative to the KiCad root).
    pub name: String,
    pub size: u64,
    /// `O1 == O2` (None when the oracle did not save it or it was skipped).
    pub fixed_point: Option<bool>,
    pub status: Status,
    /// Skip reason or oracle failure message.
    pub note: Option<String>,
    /// The evaluation, when the oracle saved the board.
    pub eval: Option<Evaluation>,
    /// Host-dependent content of `O1` that can make the byte comparison meaningless
    /// (`pcb-io.md` 9.3 skip list): outline-font render caches, embedded fonts.
    pub caveats: Vec<String>,
}

/// The caveats of an `O1` text.
pub fn caveats_of(o1: &str) -> Vec<String> {
    let mut v = Vec::new();

    if o1.contains("(render_cache ") {
        v.push("render_cache (outline fonts)".to_string());
    }

    if o1.contains("(embedded_fonts yes)") {
        v.push("embedded fonts".to_string());
    }

    v
}

/// Escape `|` for a markdown table cell and keep it on one line.
fn cell(s: &str) -> String {
    let one_line: String = s.replace('\n', " ").replace('|', "\\|");

    if one_line.chars().count() > 160 {
        let cut: String = one_line.chars().take(157).collect();
        format!("{cut}...")
    } else {
        one_line
    }
}

fn add_histogram(out: &mut String, title: &str, header: &str, rows: &BTreeMap<String, usize>) {
    let _ = writeln!(out, "## {title}\n");

    if rows.is_empty() {
        let _ = writeln!(out, "(none)\n");
        return;
    }

    let mut v: Vec<(&String, &usize)> = rows.iter().collect();
    v.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
    let _ = writeln!(out, "| {header} | boards |\n|---|---:|");

    for (k, n) in v {
        let _ = writeln!(out, "| {} | {n} |", cell(k));
    }

    out.push('\n');
}

/// Render the scoreboard (markdown).
pub fn render(results: &[BoardResult], oracle: &str) -> String {
    let mut out = String::new();
    let compared: Vec<&BoardResult> = results.iter().filter(|r| r.eval.is_some()).collect();
    let fixed = results
        .iter()
        .filter(|r| r.fixed_point == Some(true))
        .count();
    let saved = results.iter().filter(|r| r.fixed_point.is_some()).count();

    let _ = writeln!(
        out,
        "# Board reader / writer corpus scoreboard (PCBIO-17)\n"
    );
    let _ = writeln!(
        out,
        "Generated by `rust/tools/io-corpus/run.sh`. For every corpus board: O1 = oracle \
         `kicad-cli pcb upgrade --force` of the board alone, O2 = oracle re-save of O1, \
         compared with the Rust parse + format of O1 (staging: pending constructs skipped on \
         both sides).\n"
    );
    let _ = writeln!(out, "Oracle build stamp: `{oracle}`\n");
    let _ = writeln!(
        out,
        "Boards: {} ({} compared, {} skipped or rejected by the oracle). Fixed points (O1 == O2, \
         the byte-exact targets): {fixed} of {saved}.\n",
        results.len(),
        compared.len(),
        results.len() - compared.len()
    );

    let _ = writeln!(
        out,
        "## Summary\n\n| status | boards | of which fixed points |\n|---|---:|---:|"
    );

    for s in Status::ALL {
        let n = results.iter().filter(|r| r.status == s).count();
        let nf = results
            .iter()
            .filter(|r| r.status == s && r.fixed_point == Some(true))
            .count();

        if n > 0 {
            let _ = writeln!(out, "| {} | {n} | {nf} |", s.label());
        }
    }

    let with_pending = compared
        .iter()
        .filter(|r| {
            let e = r.eval.as_ref().unwrap();
            !e.parse_pending.is_empty() || !e.write_pending.is_empty() || e.model_pending.is_some()
        })
        .count();
    let _ = writeln!(
        out,
        "\nBoards with pending constructs (any side): {with_pending} of {}.\n",
        compared.len()
    );

    // Histograms (boards per key).
    let mut parse_pending: BTreeMap<String, usize> = BTreeMap::new();
    let mut write_pending: BTreeMap<String, usize> = BTreeMap::new();
    let mut model: BTreeMap<String, usize> = BTreeMap::new();
    let mut masked_first: BTreeMap<String, usize> = BTreeMap::new();
    let mut raw_first: BTreeMap<String, usize> = BTreeMap::new();
    let mut errors: BTreeMap<String, usize> = BTreeMap::new();

    for r in &compared {
        let e = r.eval.as_ref().unwrap();

        for (tok, p) in &e.parse_pending {
            *parse_pending
                .entry(format!("{tok} ({})", p.package))
                .or_default() += 1;
        }

        for (tok, p) in &e.write_pending {
            *write_pending
                .entry(format!("{tok} ({})", p.package))
                .or_default() += 1;
        }

        if let Some((stage, f)) = &e.model_pending {
            *model.entry(format!("{f} ({})", stage.label())).or_default() += 1;
        }

        if let Some(d) = &e.masked_diff {
            *masked_first.entry(d.short_label()).or_default() += 1;
        }

        if let Some(d) = &e.raw_diff {
            *raw_first.entry(d.short_label()).or_default() += 1;
        }

        if let Some(msg) = &e.error {
            *errors
                .entry(msg.lines().next().unwrap_or("").to_string())
                .or_default() += 1;
        }
    }

    add_histogram(
        &mut out,
        "Pending constructs, parser side",
        "token (package)",
        &parse_pending,
    );
    add_histogram(
        &mut out,
        "Pending constructs, writer side",
        "item (package)",
        &write_pending,
    );
    add_histogram(
        &mut out,
        "Model stubs that stopped a re-save",
        "C++ function (stage)",
        &model,
    );
    add_histogram(
        &mut out,
        "First differences after removing the pending kinds (what the ported code gets wrong)",
        "top-level block > keyword",
        &masked_first,
    );
    add_histogram(
        &mut out,
        "First differences of the full texts",
        "top-level block > keyword",
        &raw_first,
    );
    add_histogram(&mut out, "Errors and panics", "message", &errors);

    let _ = writeln!(
        out,
        "## Boards\n\n| board | KB | fixed point | status | waiting for | first difference (modulo pending) |\n|---|---:|:-:|---|---|---|"
    );

    for r in results {
        let fp = match r.fixed_point {
            Some(true) => "yes",
            Some(false) => "no",
            None => "-",
        };
        let (waiting, diff) = match &r.eval {
            Some(e) => {
                let diff = match (&e.masked_diff, &e.error) {
                    (Some(d), _) => format!("line {}: {}", d.line, d.path_label()),
                    (None, Some(m)) => m.clone(),
                    _ => String::new(),
                };
                (pending_summary(e), diff)
            }
            None => (String::new(), r.note.clone().unwrap_or_default()),
        };
        let mut status = r.status.label().to_string();

        if !r.caveats.is_empty() {
            let _ = write!(status, " ({})", r.caveats.join(", "));
        }

        let _ = writeln!(
            out,
            "| {} | {} | {fp} | {} | {} | {} |",
            cell(&r.name),
            r.size.div_ceil(1000),
            cell(&status),
            cell(&waiting),
            cell(&diff)
        );
    }

    out
}

/// The detailed report of one board (`run.sh --board`).
pub fn render_board(r: &BoardResult) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "board:       {}", r.name);
    let _ = writeln!(out, "size:        {} bytes", r.size);
    let _ = writeln!(
        out,
        "fixed point: {}",
        match r.fixed_point {
            Some(true) => "yes (O1 == O2)",
            Some(false) => "no (O2 differs from O1)",
            None => "-",
        }
    );
    let _ = writeln!(out, "status:      {}", r.status.label());

    if let Some(n) = &r.note {
        let _ = writeln!(out, "note:        {n}");
    }

    if !r.caveats.is_empty() {
        let _ = writeln!(out, "caveats:     {}", r.caveats.join(", "));
    }

    let Some(e) = &r.eval else {
        return out;
    };

    if let Some(m) = &e.error {
        let _ = writeln!(out, "error:       {m}");
    }

    if let Some((stage, f)) = &e.model_pending {
        let _ = writeln!(out, "model stub:  {f} ({})", stage.label());
    }

    for (title, map) in [
        ("parse skipped", &e.parse_pending),
        ("write skipped", &e.write_pending),
    ] {
        if !map.is_empty() {
            let items: Vec<String> = map
                .iter()
                .map(|(t, p)| format!("{t} x{} ({})", p.count, p.package))
                .collect();
            let _ = writeln!(out, "{title}: {}", items.join(", "));
        }
    }

    if !e.stripped_kinds.is_empty() {
        let _ = writeln!(
            out,
            "kinds removed for the modulo-pending comparison: {}",
            e.stripped_kinds.join(", ")
        );
    }

    if let Some(d) = &e.masked_diff {
        let _ = writeln!(
            out,
            "\nfirst difference modulo pending (line {} of the stripped texts, {}):\n{}",
            d.line,
            d.path_label(),
            d.excerpt
        );
    }

    if let Some(d) = &e.raw_diff {
        let _ = writeln!(
            out,
            "\nfirst difference of the full texts (line {}, {}):\n{}",
            d.line,
            d.path_label(),
            d.excerpt
        );
    }

    out
}
