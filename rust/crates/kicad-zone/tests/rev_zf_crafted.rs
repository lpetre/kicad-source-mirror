//! Crafted zone-fill boards of the zone filler review (package REV-ZF,
//! `rust/docs/design/review-zone-fill.md`): hand-written boards (`tests/data/rev_zf/`,
//! generated by `tests/oracle/gen_rev_zf.py`) that reach the branches of
//! `pcbnew/zone_filler.cpp` no `qa/data` board of the zone corpus reaches (custom-pad spoke
//! templates, convex-hull knockouts, hatch thermal rings around vias and every pad shape,
//! hatch smoothing levels, non-copper hatch zones, island removal by area, zones owned by
//! footprints, zones on copper and technical layers, rule-driven zone connections,
//! backdrilled and post-machined pads / vias, arc outlines, the UUID priority tie-break,
//! zones too thin for the min-width cycle, the prototype zone fill setting).
//!
//! Each board is loaded like kicad-cli (`BOARD_LOADER::Load`, with its `.kicad_pro`,
//! `.kicad_prl` and `.kicad_dru`), refilled like `ZONE_FILLER_TOOL::FillAllZones` and compared
//! with the golden `tests/golden/rev_zf/<board>.txt`: per zone layer the outline count and per
//! outline its point count, island flag and an FNV-1a hash of its vertices, taken from the
//! board the reference `kicad-cli pcb drc --refill-zones --save-board` saved
//! (`tests/oracle/make_rev_zf_goldens.sh`; `REV_ZF_BLESS=1 REV_ZF_REF_DIR=<dir>` rewrites the
//! goldens from the reference boards).
//!
//! Two boards have no reference golden because the reference does not survive them; the
//! port's behaviour there is pinned by the tests at the end of this file.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::rc::Rc;

use kicad_connectivity::data::ConnectivityData;
use kicad_core::PcbLayerId;
use kicad_drc::engine::DrcEngine;
use kicad_drc::engine::implicit_rules::TuningProfiles;
use kicad_drc::rule_parser::board_layer_choices;
use kicad_pcb::Board;
use kicad_pcb::io::{ParseOptions, parse_board};
use kicad_pcb::project::board_design_settings_json::DrcExclusionCodec;
use kicad_pcb::project::board_design_settings_json::RawDrcExclusionCodec;
use kicad_pcb::project::{LoadPath, LoadStep, StepOutcome, load_project, run_model_step};
use kicad_zone::FillAllZonesOutcome;

/// The boards whose reference refill is the golden.
const BOARDS: &[&str] = &[
    "arcs_extfillet",
    "arcs_smooth",
    "backdrill",
    "custom_spokes",
    "fp_zones",
    "hatch_noncu",
    "hatch_vias",
    "islands",
    "mixed_layers",
    "priority",
    "prototype",
    "rules_conn",
    "thin",
];

fn data_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/rev_zf")
}

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/rev_zf")
}

/// `BOARD_LOADER::Load` as kicad-cli runs it (project with its local settings, custom rules,
/// DRC engine, connectivity), then `ZONE_FILLER_TOOL::FillAllZones( nullptr, reporter, true )`.
fn load_and_fill(path: &Path) -> (Board, FillAllZonesOutcome) {
    let text = std::fs::read_to_string(path).unwrap();
    let name = path.to_str().unwrap();
    let mut board = parse_board(&text, name, &ParseOptions::default()).unwrap();
    board.file_name = name.to_string();
    kicad_drc::component_class_rules::install(&mut board);

    let pro_path = path.with_extension("kicad_pro");
    let pro = std::fs::read_to_string(&pro_path).ok();
    let prl = std::fs::read_to_string(path.with_extension("kicad_prl")).ok();
    let project = load_project(pro.as_deref(), prl.as_deref(), pro_path.to_str().unwrap());
    let rules_path = path.with_extension("kicad_dru");
    let rules = std::fs::read_to_string(&rules_path).ok();

    let mut engine = DrcEngine::new();
    let mut connectivity = ConnectivityData::new();
    let codec: Rc<dyn DrcExclusionCodec> = Rc::new(RawDrcExclusionCodec);
    let mut project = Some(project);

    for &step in LoadPath::Cli.steps() {
        let outcome =
            run_model_step(&mut board, LoadPath::Cli, step, &mut project, &codec).unwrap();

        if outcome == StepOutcome::Session {
            match step {
                LoadStep::InitDrcEngine => {
                    let layer_choices = board_layer_choices(&board);
                    let _ = engine.init_engine(
                        &mut board,
                        rules.as_deref().map(|t| (t, rules_path.to_str().unwrap())),
                        layer_choices,
                        &TuningProfiles::default(),
                        None,
                    );
                }
                LoadStep::BuildConnectivity => {
                    connectivity.build_connectivity(&mut board);
                }
                _ => {}
            }
        }
    }

    let outcome = kicad_zone::fill_all_zones(&mut board, &mut connectivity, &engine);
    (board, outcome)
}

fn fnv1a(hash: &mut u64, value: i32) {
    for byte in value.to_le_bytes() {
        *hash ^= byte as u64;
        *hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
}

/// The golden text of a filled board: every zone (board and footprint zones, by name), every
/// layer of its layer set, every outline.
fn golden_text(board: &Board) -> String {
    let mut zones: BTreeMap<String, String> = BTreeMap::new();

    for zone_id in board.get_zone_list(true) {
        let zone = board.zone(zone_id).unwrap();

        if zone.is_rule_area() {
            continue;
        }

        let mut text = String::new();

        for layer in zone.layer_set.iter() {
            let layer: PcbLayerId = layer;
            let outlines = zone.get_fill(layer).map_or(0, |f| f.outline_count());
            let _ = writeln!(
                text,
                "zone {} {layer:?} outlines {outlines}",
                zone.zone_name()
            );

            let Some(fill) = zone.get_fill(layer) else {
                continue;
            };

            for ii in 0..outlines {
                let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
                let mut points = 0;

                for contour in fill.c_polygon(ii) {
                    for pt in contour.c_points() {
                        fnv1a(&mut hash, pt.x);
                        fnv1a(&mut hash, pt.y);
                        points += 1;
                    }
                }

                let _ = writeln!(
                    text,
                    "  {ii} pts {points} island {} hash {hash:016x}",
                    zone.is_island(layer, ii) as u8
                );
            }
        }

        let previous = zones.insert(zone.zone_name().to_string(), text);
        assert!(previous.is_none(), "zone names must be unique");
    }

    zones.into_values().collect()
}

/// `REV_ZF_BLESS=1 REV_ZF_REF_DIR=<target/zone-corpus-rev>`: rewrite the goldens from the
/// boards the reference saved.
fn bless() {
    let ref_dir = PathBuf::from(std::env::var("REV_ZF_REF_DIR").expect("REV_ZF_REF_DIR"));
    std::fs::create_dir_all(golden_dir()).unwrap();

    for name in BOARDS {
        let path = ref_dir
            .join(name)
            .join("ref")
            .join(format!("{name}.kicad_pcb"));
        let Ok(text) = std::fs::read_to_string(&path) else {
            println!("{name}: no reference board at {}", path.display());
            continue;
        };

        let board = parse_board(&text, "ref.kicad_pcb", &ParseOptions::default()).unwrap();
        std::fs::write(
            golden_dir().join(format!("{name}.txt")),
            golden_text(&board),
        )
        .unwrap();
    }
}

#[test]
fn rev_zf_crafted_boards_match_the_reference() {
    if std::env::var("REV_ZF_BLESS").is_ok_and(|v| v == "1") {
        bless();
    }

    let mut failures = String::new();

    for name in BOARDS {
        let golden = std::fs::read_to_string(golden_dir().join(format!("{name}.txt")))
            .unwrap_or_else(|_| panic!("missing golden of {name}"));
        let (board, outcome) = load_and_fill(&data_dir().join(format!("{name}.kicad_pcb")));
        let actual = golden_text(&board);

        assert!(outcome.filled);
        assert!(
            outcome.warnings.is_empty(),
            "{name}: {:?}",
            outcome.warnings
        );

        if actual != golden {
            let first = golden
                .lines()
                .zip(actual.lines())
                .find(|(g, a)| g != a)
                .map(|(g, a)| format!("expected `{g}`, got `{a}`"))
                .unwrap_or_else(|| "different line counts".to_string());
            let _ = writeln!(failures, "{name}: {first}");
        } else {
            println!(
                "{name}: {} zone layers identical",
                golden.matches("zone ").count()
            );
        }
    }

    assert!(failures.is_empty(), "\n{failures}");
}

/// Finding F-1: a zone on a copper layer and a technical layer whose copper fill is isolated.
/// The connectivity maps the technical layer's zone item to copper ordinal 0
/// (`CN_ITEM::SetLayers`), so `FillIsolatedIslandsMap` lists outline 0 twice under F.Cu and
/// the C++ deletes it twice: undefined behaviour, the reference kicad-cli segfaults in
/// `SHAPE_POLY_SET::DeletePolygonAndTriangulationData`. The port deletes the outline once.
#[test]
fn rev_zf_mixed_layer_zone_with_isolated_copper_does_not_panic() {
    let (board, outcome) = load_and_fill(&data_dir().join("mixed_isolated.kicad_pcb"));
    assert!(outcome.filled);

    let zone_id = board.get_zone_list(false)[0];
    let zone = board.zone(zone_id).unwrap();

    assert_eq!(zone.get_fill(PcbLayerId::FCu).unwrap().outline_count(), 0);
    assert_eq!(
        zone.get_fill(PcbLayerId::FSilkS).unwrap().outline_count(),
        1
    );
}

/// Finding F-2: two interacting zones of different nets with equal priority and the same
/// UUID. Neither is `HigherPriority()`, each waits for the other in the C++ fill scheduler
/// and the reference kicad-cli never returns. The port fills both (neither knocks the other
/// out, as the C++ fill functions would compute) and reports the cycle.
#[test]
fn rev_zf_duplicate_zone_uuids_terminate() {
    let (board, outcome) = load_and_fill(&data_dir().join("dup_uuid.kicad_pcb"));
    assert!(outcome.filled);
    assert_eq!(outcome.warnings.len(), 1, "{:?}", outcome.warnings);
    assert!(outcome.warnings[0].contains("dependency cycle"));

    for zone_id in board.get_zone_list(false) {
        let zone = board.zone(zone_id).unwrap();
        assert_eq!(zone.get_fill(PcbLayerId::FCu).unwrap().outline_count(), 1);
    }
}
