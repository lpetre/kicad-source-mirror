#!/bin/sh
# Runs the spatial differential test of kicad-geom against the C++ oracle (see
# spatial_oracle.cpp and ../oracle_spatial.rs) for a wasm32-unknown-unknown build of the
# crate, under node.js.  No section depends on libm, so all must match bit for bit.
#
# Usage: ./run_wasm_spatial_check.sh  (needs cargo with the wasm32-unknown-unknown target, and node)
set -eu

here=$(cd "$(dirname "$0")" && pwd)
crate=$(cd "$here/../.." && pwd)
rust=$(cd "$crate/../.." && pwd)
work=${GEOM_ORACLE_BUILD_DIR:-$rust/target/geom-oracle}/wasm-spatial-check

mkdir -p "$work/src"

cat > "$work/Cargo.toml" <<TOML
[package]
name = "kicad-geom-wasm-spatial-check"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib"]

[workspace]

[dependencies]
kicad-geom = { path = "$crate" }

[profile.release]
opt-level = 2
TOML

cat > "$work/src/lib.rs" <<RS
//! Scratch crate generated by run_wasm_check.sh: exports the oracle sections to node.js.
use std::sync::Mutex;

#[path = "$here/spatial_sections.rs"]
mod spatial_sections;

static RESULTS: Mutex<Vec<(String, u64, u64)>> = Mutex::new(Vec::new());

/// Run all sections; returns their number.
#[unsafe(no_mangle)]
pub extern "C" fn run() -> u32 {
    let mut results = spatial_sections::Results { sections: Vec::new(), dump: None };
    spatial_sections::run_all(&mut results);
    let n = results.sections.len() as u32;
    *RESULTS.lock().unwrap() = results.sections;
    n
}

#[unsafe(no_mangle)]
pub extern "C" fn cases(i: u32) -> u32 {
    RESULTS.lock().unwrap()[i as usize].1 as u32
}

#[unsafe(no_mangle)]
pub extern "C" fn hash_hi(i: u32) -> u32 {
    (RESULTS.lock().unwrap()[i as usize].2 >> 32) as u32
}

#[unsafe(no_mangle)]
pub extern "C" fn hash_lo(i: u32) -> u32 {
    RESULTS.lock().unwrap()[i as usize].2 as u32
}
RS

cat > "$work/check.js" <<'JS'
const fs = require('fs');
const [wasmPath, goldenPath] = process.argv.slice(2);
const instance = new WebAssembly.Instance(new WebAssembly.Module(fs.readFileSync(wasmPath)), {});
const golden = fs.readFileSync(goldenPath, 'utf8').trim().split('\n').map((l) => l.trim().split(/\s+/));
const n = instance.exports.run();
let failed = false;

if (n !== golden.length) {
    console.log(`section count differs: ${n} vs ${golden.length}`);
    process.exit(1);
}

for (let i = 0; i < n; i++) {
    const [name, count, hash] = golden[i];
    const hex = (v) => (v >>> 0).toString(16).padStart(8, '0');
    const ours = hex(instance.exports.hash_hi(i)) + hex(instance.exports.hash_lo(i));
    const same = ours === hash && (instance.exports.cases(i) >>> 0) === Number(count);
    const libm = name.startsWith('libm');

    if (same) {
        console.log(`ok        ${name} (${count} cases)`);
    } else if (libm) {
        console.log(`differs   ${name} (${count} cases) - libm dependent, expected on wasm32`);
    } else {
        console.log(`MISMATCH  ${name}: got ${ours}, expected ${hash}`);
        failed = true;
    }
}

process.exit(failed ? 1 : 0);
JS

(cd "$work" && cargo build --release --target wasm32-unknown-unknown --quiet)

node "$work/check.js" "$work/target/wasm32-unknown-unknown/release/kicad_geom_wasm_spatial_check.wasm" \
    "$crate/tests/golden/spatial_oracle.txt"
