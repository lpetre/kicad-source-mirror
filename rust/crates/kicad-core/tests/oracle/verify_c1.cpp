// Second, independent differential-test oracle for the kicad-core Rust port (work package C1).
//
// It complements core_oracle.cpp: where that program samples, this one enumerates.  Every
// PCB_LAYER_ID enumerator, every static LSET mask and every ordering function is dumped element
// by element; FlipLayer / FlipStandardLayers / LayerCount / IsBetween / LAYER_RANGE are swept
// over their whole (small) domains; the KIID string constructor, KIID_PATH, LIB_ID, BASE_SET and
// LSET::NameToLayer are fuzzed with generated strings.
//
// The dump (tests/golden/verify_c1_dump.txt) is regenerated by tests/test_verify_c1.rs with the
// Rust port and compared line by line.  Build with tests/oracle/build_oracle.sh.
//
// Inputs that are undefined behaviour in C++ (out of range bit tests, KIID( timestamp_t ) with
// Boost < 1.86, FlipStandardLayers with more than 64 copper layers) are left out.  LAYER_RANGEs
// on which the C++ iterator never terminates are detected with a step limit and recorded as
// such; the Rust test only requires the port to terminate on them.
